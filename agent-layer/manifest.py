"""Agent-layer integration manifest: every file OC3 copies, with shas and targets.

Regenerate: python3 agent-layer/manifest.py > agent-layer/MANIFEST.md
Test test_manifest_fresh asserts the committed manifest matches the tree.
"""
import hashlib
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)

TARGETS = {
    "agent-layer/units/oc2-queue.service": "~/.config/systemd/user/oc2-queue.service",
    "agent-layer/units/oc2-patrol.service": "~/.config/systemd/user/oc2-patrol.service",
    "agent-layer/units/oc2-patrol.timer": "~/.config/systemd/user/oc2-patrol.timer",
    "agent-layer/units/oc2-trio.service": "~/.config/systemd/user/oc2-trio.service",
    "agent-layer/install.sh": "run: sh agent-layer/install.sh (idempotent)",
    "agent-layer/env.example": "~/.config/oc2-agent/env (template only, never keys)",
    "agent-layer/README.md": "docs (not installed)",
}

VERIFY = [
    "systemctl --user list-unit-files | grep oc2- (4 units enabled)",
    "systemctl --user is-active oc2-queue oc2-trio (active, no login needed)",
    "journalctl --user -b -u oc2-queue -u oc2-trio -u oc2-patrol | grep -c Started (>=3)",
    "SPARK_API_KEY must NOT appear in any installed file (grep -r $HOME/.config/systemd/user/)",
]


def main():
    print("# OC2 agent-layer integration manifest")
    print("# Generated by agent-layer/manifest.py — do not hand-edit.")
    print("# OC3 copies these paths; shas must match at copy time.")
    print()
    for rel in sorted(TARGETS):
        p = os.path.join(_REPO, rel)
        h = hashlib.sha256(open(p, "rb").read()).hexdigest()
        print(f"- `{rel}` sha256 `{h}` → {TARGETS[rel]}")
    print()
    print("## Verify after install")
    for v in VERIFY:
        print(f"- [ ] `{v}`")


if __name__ == "__main__":
    main()
