//! KF-10 desktop icons, Meta set (Del approved the look
//! 2026-11-03): sixteen glyph bitmaps in Meta blues, drawn by the
//! kernel on white tiles in the desktop dock.
//!
//! The set is the face's own dock, copied exactly: the list, order,
//! labels and the two separators come from the `DOCK` array in
//! face/face.js (line 453). The glyphs are the same Unicode glyphs
//! the face names (terminal U+232A, dashboard U+25A6, files
//! U+1F4C1, notes U+1F4DD, calendar U+1F4C5, calculator U+1F5A9,
//! board U+270E, imperium U+26E8, musica U+266B, science U+2697,
//! officina U+1F527, aegis U+1F6E1, nervus U+1F9E0, settings
//! U+2699, trash U+1F5D1, about U+24D8), rendered off-line and
//! recolored into Meta blues (navy, #1877F2, light blue), because
//! the bare-metal kernel has no browser, no emoji font and no
//! image loader. Each rendered glyph was cropped to its bounding
//! box and sampled to a 48x48 character grid (generator:
//! gen_icons_rs.py, run by Pax); `.` is transparent and
//! `b`/`B`/`L` are the three blues of the framebuffer palette.
//! The white tile is painted in code by `draw_dock`, not stored
//! in the bitmap, so the glyph gets the full grid. This is the
//! bitmap route Del picked for getting the face's icons into
//! the OS.
//!
//! Icons are decorative at this milestone: there is no mouse or
//! click handling in the kernel yet (KF-12/KF-13 territory).
//!
//! Status: compiles with framebuffer.rs (rustc 1.99.1, core-only
//! lib check, Pax). The full kernel build and a QEMU screendump
//! showing the dock remain the Mac-side proof, owed together with
//! the KF-10 window proof.

