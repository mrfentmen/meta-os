/// Width of one glyph cell, in pixels.
pub const FONT_WIDTH: usize = 8;

/// Height of one glyph cell, in pixels.
pub const FONT_HEIGHT: usize = 16;

/// Pixel layout of a framebuffer, as the R5 adapter will report it.
/// `stride` is in pixels, matching the framebuffer-info convention;
/// `byte_len` is the total buffer length the adapter measured.
#[derive(Clone, Copy)]
pub struct FramebufferInfo {
    pub width: usize,
    pub height: usize,
    pub stride: usize,
    pub bytes_per_pixel: usize,
    pub pixel_format: PixelFormat,
    pub byte_len: usize,
}

/// Pixel channel order. `Gray` is a single byte per pixel.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum PixelFormat {
    /// Red, green, blue in memory order (plus an opaque pad byte at 4 bpp).
    Rgb,
    /// Blue, green, red in memory order (plus an opaque pad byte at 4 bpp).
    Bgr,
    /// One byte per pixel, luminance only.
    Gray,
    /// A format the adapter could not map (bootloader `Unknown` or a
    /// depth this module does not paint). `write_pixel` leaves every
    /// pixel unwritten for this format — never a guessed layout.
    Unsupported,
}

/// A framebuffer console buffer. All writes are bounds-checked against
/// the geometry and the supplied slice: a short buffer clips drawing,
/// it never writes out of bounds. That is deliberate: the R5 adapter
/// hands over whatever the bootloader reported, and a mismatch must
/// degrade to a clipped screen, not to memory corruption.
pub struct Framebuffer<'a> {
    buffer: &'a mut [u8],
    info: FramebufferInfo,
}

impl<'a> Framebuffer<'a> {
    /// Wrap a caller-supplied pixel buffer. No pixel is touched here;
    /// clearing is the console constructor's job, so a bare buffer
    /// can be inspected before any draw.
    pub fn new(buffer: &'a mut [u8], info: FramebufferInfo) -> Self {
        Framebuffer { buffer, info }
    }

    /// Geometry the adapter reported, for the console's column/row math.
    pub fn info(&self) -> FramebufferInfo {
        self.info
    }

    /// Byte offset of pixel (`x`, `y`), or `None` when the pixel is
    /// outside the geometry or outside the supplied slice.
    fn pixel_offset(&self, x: usize, y: usize) -> Option<usize> {
        if x >= self.info.width || y >= self.info.height {
            return None;
        }
        let bpp = self.info.bytes_per_pixel;
        if bpp == 0 {
            return None;
        }
        let offset = y
            .checked_mul(self.info.stride)?
            .checked_mul(bpp)?
            .checked_add(x.checked_mul(bpp)?)?;
        if offset.checked_add(bpp)? > self.buffer.len() {
            return None;
        }
        Some(offset)
    }

    /// Plot one pixel. Unknown depths (anything other than 1, 3, or 4
    /// bytes per pixel) are left unwritten: this module will not guess
    /// a layout it does not know. At 4 bytes per pixel the pad byte is
    /// set opaque so a compositor never sees a transparent pixel.
    pub fn write_pixel(&mut self, x: usize, y: usize, color: (u8, u8, u8)) {
        let offset = match self.pixel_offset(x, y) {
            Some(offset) => offset,
            None => return,
        };
        let (r, g, b) = color;
        match (self.info.pixel_format, self.info.bytes_per_pixel) {
            (PixelFormat::Gray, 1) => {
                let lum = ((r as u16 * 30 + g as u16 * 59 + b as u16 * 11) / 100) as u8;
                self.buffer[offset] = lum;
            }
            (PixelFormat::Rgb, 3) => {
                self.buffer[offset] = r;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = b;
            }
            (PixelFormat::Bgr, 3) => {
                self.buffer[offset] = b;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = r;
            }
            (PixelFormat::Rgb, 4) => {
                self.buffer[offset] = r;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = b;
                self.buffer[offset + 3] = 0xFF;
            }
            (PixelFormat::Bgr, 4) => {
                self.buffer[offset] = b;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = r;
                self.buffer[offset + 3] = 0xFF;
            }
            _ => {}
        }
    }

    /// Fill the whole screen with one color.
    pub fn clear(&mut self, color: (u8, u8, u8)) {
        for y in 0..self.info.height {
            for x in 0..self.info.width {
                self.write_pixel(x, y, color);
            }
        }
    }

    /// Fill a pixel rectangle, clipped to the screen by `write_pixel`.
    pub fn fill_rect(&mut self, x: usize, y: usize, w: usize, h: usize, color: (u8, u8, u8)) {
        for row in y..y.saturating_add(h) {
            for col in x..x.saturating_add(w) {
                self.write_pixel(col, row, color);
            }
        }
    }

    /// Scroll the screen up by `lines` pixel rows: every row moves up
    /// and the freed rows at the bottom are painted `fill`. Each
    /// destination row's bytes are copied from the source row below it
    /// with `copy_within`, which handles the overlap; the destination
    /// is always above the source, so no row is read after overwrite.
    pub fn scroll_up_pixels(&mut self, lines: usize, fill: (u8, u8, u8)) {
        if lines == 0 || lines >= self.info.height {
            if lines >= self.info.height && self.info.height > 0 {
                self.clear(fill);
            }
            return;
        }
        let bpp = self.info.bytes_per_pixel;
        if bpp == 0 {
            return;
        }
        let row_bytes = self.info.stride.saturating_mul(bpp);
        let height = self.info.height;
        for y in 0..height - lines {
            let dst = y.saturating_mul(row_bytes);
            let src = y.saturating_add(lines).saturating_mul(row_bytes);
            if src.checked_add(row_bytes).map_or(true, |end| end > self.buffer.len())
                || dst.checked_add(row_bytes).map_or(true, |end| end > self.buffer.len())
            {
                continue;
            }
            // Copy within the slice, destination above source: safe in order.
            self.buffer.copy_within(src..src + row_bytes, dst);
        }
        self.fill_rect(0, height - lines, self.info.width, lines, fill);
    }

    /// Scroll a pixel rectangle up by `lines` pixel rows, painting the
    /// freed rows at the rectangle's bottom with `fill` (KF-10: the
    /// shell window scrolls its own interior, not the whole screen, so
    /// the desktop and window frame around it stay put). The rectangle
    /// is clamped to the screen geometry first; each row segment is
    /// then copied with `copy_within`, destination above source, so no
    /// row is read after it is overwritten.
    pub fn scroll_up_rect_pixels(
        &mut self,
        x: usize,
        y: usize,
        w: usize,
        h: usize,
        lines: usize,
        fill: (u8, u8, u8),
    ) {
        if x >= self.info.width || y >= self.info.height || w == 0 || h == 0 || lines == 0 {
            return;
        }
        let w = w.min(self.info.width - x);
        let h = h.min(self.info.height - y);
        if lines >= h {
            self.fill_rect(x, y, w, h, fill);
            return;
        }
        let bpp = self.info.bytes_per_pixel;
        if bpp == 0 {
            return;
        }
        let stride_bytes = self.info.stride.saturating_mul(bpp);
        let seg_bytes = w.saturating_mul(bpp);
        for row in 0..(h - lines) {
            let dst = (y + row)
                .saturating_mul(stride_bytes)
                .saturating_add(x.saturating_mul(bpp));
            let src = (y + row + lines)
                .saturating_mul(stride_bytes)
                .saturating_add(x.saturating_mul(bpp));
            if src.checked_add(seg_bytes).map_or(true, |end| end > self.buffer.len())
                || dst.checked_add(seg_bytes).map_or(true, |end| end > self.buffer.len())
            {
                continue;
            }
            self.buffer.copy_within(src..src + seg_bytes, dst);
        }
        self.fill_rect(x, y + h - lines, w, lines, fill);
    }

    /// Draw a character bitmap (KF-10 icons): one character per
    /// pixel, each painted as a `scale` x `scale` block. `.` is
    /// transparent and leaves the pixels underneath untouched; every
    /// other character maps through `icon_color`. Rows shorter than
    /// others simply end early; everything is clipped by
    /// `write_pixel`, so a bitmap hanging off an edge is safe.
    pub fn draw_bitmap(&mut self, x: usize, y: usize, scale: usize, rows: &[&str]) {
        if scale == 0 {
            return;
        }
        for (row, line) in rows.iter().enumerate() {
            for (col, ch) in line.bytes().enumerate() {
                if let Some(color) = icon_color(ch) {
                    self.fill_rect(x + col * scale, y + row * scale, scale, scale, color);
                }
            }
        }
    }

    /// Draw one glyph cell with its top-left corner at pixel (`x`, `y`).
    /// Bit 7 of each font byte is the leftmost pixel. Every pixel of
    /// the cell is painted, foreground for set bits and background for
    /// clear bits, so a redrawn cell never leaves stale pixels behind.
    pub fn draw_glyph(&mut self, x: usize, y: usize, ch: u8, fg: (u8, u8, u8), bg: (u8, u8, u8)) {
        let glyph = FONT_8X16[ch as usize];
        for row in 0..FONT_HEIGHT {
            let bits = glyph[row];
            for col in 0..FONT_WIDTH {
                let set = bits & (0x80 >> col) != 0;
                self.write_pixel(x + col, y + row, if set { fg } else { bg });
            }
        }
    }
}

/// Palette for the KF-10 icon bitmaps (icons.rs). One character per
/// color so icon data stays readable as ASCII art in the source.
/// `B` is the Meta blue from the repo's own icon contract
/// (metaos-theme/icons/ICONS.md maps folder blue to #1877F2).
/// Anything unlisted — including `.` — is transparent.
fn icon_color(ch: u8) -> Option<(u8, u8, u8)> {
    match ch {
        b'K' => Some((0, 0, 0)),
        b'W' => Some((255, 255, 255)),
        b'B' => Some((24, 119, 242)),
        b'b' => Some((0, 0, 170)),
        b'L' => Some((85, 85, 255)),
        b'G' => Some((140, 140, 140)),
        b'D' => Some((70, 70, 70)),
        b'R' => Some((205, 45, 45)),
        b'N' => Some((35, 175, 70)),
        b'Y' => Some((245, 197, 66)),
        b'O' => Some((232, 140, 35)),
        b'C' => Some((60, 190, 220)),
        _ => None,
    }
}

/// A text console over a framebuffer: character cells, a cursor, and
/// scrolling. Columns and rows are derived from the geometry, so a
/// framebuffer narrower than one glyph cell yields zero columns and
/// every write is a no-op rather than a wrap-around bug.
pub struct FramebufferConsole<'a> {
    fb: Framebuffer<'a>,
    col: usize,
    row: usize,
    fg: (u8, u8, u8),
    bg: (u8, u8, u8),
    // KF-10 view region: text is drawn inside this pixel rectangle
    // (origin + size) and scrolls inside it. Default is the whole
    // screen, which reproduces the KF-03 full-screen console exactly;
    // `draw_shell_desktop` narrows it to the shell window's interior.
    origin_x: usize,
    origin_y: usize,
    view_w: usize,
    view_h: usize,
}

impl<'a> FramebufferConsole<'a> {
    /// Build a console and clear the screen to the background color.
    pub fn new(fb: Framebuffer<'a>, fg: (u8, u8, u8), bg: (u8, u8, u8)) -> Self {
        let (w, h) = (fb.info().width, fb.info().height);
        let mut console = FramebufferConsole {
            fb,
            col: 0,
            row: 0,
            fg,
            bg,
            origin_x: 0,
            origin_y: 0,
            view_w: w,
            view_h: h,
        };
        let bg_color = console.bg;
        console.fb.clear(bg_color);
        console
    }

    /// Character columns across the view region (zero on a sub-cell view).
    pub fn cols(&self) -> usize {
        self.view_w / FONT_WIDTH
    }

    /// Character rows down the view region (zero on a sub-cell view).
    pub fn rows(&self) -> usize {
        self.view_h / FONT_HEIGHT
    }

    /// Narrow the text view to a pixel rectangle (KF-10: the shell
    /// window's interior). The rectangle is clamped to the screen; the
    /// cursor restarts at the region's top-left cell. Drawing, wrapping
    /// and scrolling all stay inside the region from here on.
    pub fn set_view(&mut self, x: usize, y: usize, w: usize, h: usize) {
        let (sw, sh) = (self.fb.info().width, self.fb.info().height);
        self.origin_x = x.min(sw);
        self.origin_y = y.min(sh);
        self.view_w = w.min(sw - self.origin_x);
        self.view_h = h.min(sh - self.origin_y);
        self.col = 0;
        self.row = 0;
    }

    /// Restore the whole-screen view (KF-10: the panic handler calls
    /// this first, so a panic paints the full screen, not the window).
    pub fn full_view(&mut self) {
        let (w, h) = (self.fb.info().width, self.fb.info().height);
        self.origin_x = 0;
        self.origin_y = 0;
        self.view_w = w;
        self.view_h = h;
        self.col = 0;
        self.row = 0;
    }

    /// Draw a text string with its first glyph cell at pixel (`x`, `y`),
    /// independent of the cursor and the view region (KF-10: window
    /// titles and the desktop top bar are painted, not typed).
    pub fn draw_text_px(&mut self, x: usize, y: usize, s: &str, fg: (u8, u8, u8), bg: (u8, u8, u8)) {
        for (i, byte) in s.bytes().enumerate() {
            self.fb
                .draw_glyph(x + i * FONT_WIDTH, y, byte, fg, bg);
        }
    }

    /// Screen geometry in pixels (KF-10: the dock layout in icons.rs
    /// sizes itself from this, not from assumed dimensions).
    pub fn screen_size(&self) -> (usize, usize) {
        let info = self.fb.info();
        (info.width, info.height)
    }

    /// Fill a pixel rectangle straight on the framebuffer, bypassing
    /// the text view and cursor (KF-10: dock bar and other painted
    /// desktop furniture).
    pub fn fill_rect_px(&mut self, x: usize, y: usize, w: usize, h: usize, color: (u8, u8, u8)) {
        self.fb.fill_rect(x, y, w, h, color);
    }

    /// Draw an icon bitmap straight on the framebuffer (KF-10:
    /// icons.rs dock), bypassing the text view and cursor.
    pub fn draw_bitmap_px(&mut self, x: usize, y: usize, scale: usize, rows: &[&str]) {
        self.fb.draw_bitmap(x, y, scale, rows);
    }

    /// Paint the KF-10 desktop and the shell window, then narrow this
    /// console's view to the window's interior so the real shell
    /// (sched.rs console task, reached through the normal `print!`
    /// path) types inside the window from here on. The kernel draws
    /// every pixel itself: light desktop, white top bar with the OS
    /// name, one centred window with a blue title bar and a black
    /// interior. Returns false without painting when the screen is
    /// too small to hold a usable window, so boot degrades to the
    /// KF-03 full-screen console instead of a broken desktop.
    pub fn draw_shell_desktop(&mut self) -> bool {
        let (sw, sh) = (self.fb.info().width, self.fb.info().height);
        if sw < 320 || sh < 200 {
            return false;
        }
        const DESKTOP: (u8, u8, u8) = (148, 178, 216);
        const BAR: (u8, u8, u8) = (242, 244, 248);
        const INK: (u8, u8, u8) = (0, 0, 0);
        const TITLE: (u8, u8, u8) = (0, 0, 170);
        const WHITE: (u8, u8, u8) = (255, 255, 255);
        const SHADOW: (u8, u8, u8) = (70, 84, 104);
        // Desktop and top bar.
        self.fb.clear(DESKTOP);
        self.fb.fill_rect(0, 0, sw, 28, BAR);
        self.draw_text_px(12, 6, "META OS 0.1", INK, BAR);
        // One centred window: drop shadow, white frame, blue title
        // bar, black interior.
        let win_w = (sw - 96).min(920);
        let win_h = (sh - 190).min(540);
        let win_x = (sw - win_w) / 2;
        let win_y = 76usize;
        self.fb.fill_rect(win_x + 10, win_y + 10, win_w, win_h, SHADOW);
        self.fb.fill_rect(win_x, win_y, win_w, win_h, WHITE);
        self.fb.fill_rect(win_x + 2, win_y + 2, win_w - 4, win_h - 4, INK);
        self.fb.fill_rect(win_x + 2, win_y + 2, win_w - 4, 26, TITLE);
        self.draw_text_px(win_x + 12, win_y + 7, "META OS SHELL", WHITE, TITLE);
        // The shell lives in the interior below the title bar.
        self.set_view(win_x + 14, win_y + 40, win_w - 28, win_h - 52);
        self.set_colors((170, 170, 170), INK);
        self.clear();
        true
    }

    /// Move the cursor (demo splash: lets the boot spin redraw the
    /// same rows instead of scrolling; mirrors vga.rs set_pos).
    /// Clamped inside the screen; a sub-cell screen parks at 0,0.
    pub fn set_pos(&mut self, row: usize, col: usize) {
        if self.rows() == 0 || self.cols() == 0 {
            self.row = 0;
            self.col = 0;
            return;
        }
        self.row = row.min(self.rows() - 1);
        self.col = col.min(self.cols() - 1);
    }

    /// Move to the start of the next line, scrolling when past the bottom.
    fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        if self.row >= self.rows() {
            if self.rows() > 0 {
                let bg_color = self.bg;
                let (ox, oy, vw, vh) = (self.origin_x, self.origin_y, self.view_w, self.view_h);
                self.fb
                    .scroll_up_rect_pixels(ox, oy, vw, vh, FONT_HEIGHT, bg_color);
                self.row = self.rows() - 1;
            } else {
                self.row = 0;
            }
        }
    }

    /// Write one byte. `\n` moves to the next line, `\r` returns to
    /// column zero, `0x08` backspaces (KF-03: the shell erases with
    /// the "\x08 \x08" sequence, so the framebuffer console must
    /// blank the cell like vga.rs does, not ignore the byte),
    /// printable and high bytes (0x20..=0xFF) draw their
    /// glyph from the 256-entry table, and other control bytes are
    /// ignored rather than drawn as glyph noise.
    pub fn write_byte(&mut self, byte: u8) {
        match byte {
            b'\n' => self.newline(),
            b'\r' => self.col = 0,
            0x08 => self.backspace(),
            0x20..=0xFF => {
                if self.cols() == 0 || self.rows() == 0 {
                    return;
                }
                let x = self.origin_x + self.col * FONT_WIDTH;
                let y = self.origin_y + self.row * FONT_HEIGHT;
                let fg_color = self.fg;
                let bg_color = self.bg;
                self.fb.draw_glyph(x, y, byte, fg_color, bg_color);
                self.col += 1;
                if self.col >= self.cols() {
                    self.newline();
                }
            }
            _ => {}
        }
    }

    /// Write a string, byte by byte. Non-ASCII UTF-8 bytes draw their
    /// Latin-2 glyphs individually; this is a byte console, not a
    /// Unicode renderer, and that limit is stated, not hidden.
    pub fn write_str(&mut self, s: &str) {
        for byte in s.bytes() {
            self.write_byte(byte);
        }
    }

    /// Erase the cell left of the cursor (KF-03, mirrors
    /// vga.rs backspace): move back one cell and repaint it with
    /// the background color. At column 0, wrap to the previous
    /// row's last cell; at the top-left cell, a no-op. On a
    /// sub-cell screen (zero columns) there is no cell to erase.
    pub fn backspace(&mut self) {
        if self.cols() == 0 {
            return;
        }
        if self.col > 0 {
            self.col -= 1;
        } else if self.row > 0 {
            self.row -= 1;
            self.col = self.cols() - 1;
        } else {
            return;
        }
        let bg = self.bg;
        let (x, y) = (
            self.origin_x + self.col * FONT_WIDTH,
            self.origin_y + self.row * FONT_HEIGHT,
        );
        self.fb.draw_glyph(x, y, b' ', bg, bg);
    }

    /// Fill the view region with the background color and restart the
    /// cursor at its top-left cell (KF-03: the shell `clear` command
    /// and the panic screen need this on the framebuffer exactly as
    /// they have it on VGA; KF-10: in the shell window this blanks
    /// only the window's interior, the desktop stays painted).
    pub fn clear(&mut self) {
        let bg = self.bg;
        let (ox, oy, vw, vh) = (self.origin_x, self.origin_y, self.view_w, self.view_h);
        let (sw, sh) = (self.fb.info().width, self.fb.info().height);
        if ox == 0 && oy == 0 && vw == sw && vh == sh {
            self.fb.clear(bg);
        } else {
            self.fb.fill_rect(ox, oy, vw, vh, bg);
        }
        self.col = 0;
        self.row = 0;
    }

    /// Change colors; already-drawn cells keep their colors
    /// (KF-03: mirrors vga.rs set_colors for the panic screen and
    /// the shell status block).
    pub fn set_colors(&mut self, fg: (u8, u8, u8), bg: (u8, u8, u8)) {
        self.fg = fg;
        self.bg = bg;
    }
}

