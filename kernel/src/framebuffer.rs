/// Width of one glyph cell, in pixels.
pub const FONT_WIDTH: usize = 8;

/// Height of one glyph cell, in pixels.
pub const FONT_HEIGHT: usize = 16;

/// Pixel layout of a framebuffer, as the R5 adapter will report it.
/// `stride` is in pixels, matching the framebuffer-info convention;
/// `byte_len` is the total buffer length the adapter measured.
#[derive(Clone, Copy)]
pub struct FramebufferInfo {
    pub width: usize,
    pub height: usize,
    pub stride: usize,
    pub bytes_per_pixel: usize,
    pub pixel_format: PixelFormat,
    pub byte_len: usize,
}

/// Pixel channel order. `Gray` is a single byte per pixel.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum PixelFormat {
    /// Red, green, blue in memory order (plus an opaque pad byte at 4 bpp).
    Rgb,
    /// Blue, green, red in memory order (plus an opaque pad byte at 4 bpp).
    Bgr,
    /// One byte per pixel, luminance only.
    Gray,
    /// A format the adapter could not map (bootloader `Unknown` or a
    /// depth this module does not paint). `write_pixel` leaves every
    /// pixel unwritten for this format — never a guessed layout.
    Unsupported,
}

/// A framebuffer console buffer. All writes are bounds-checked against
/// the geometry and the supplied slice: a short buffer clips drawing,
/// it never writes out of bounds. That is deliberate: the R5 adapter
/// hands over whatever the bootloader reported, and a mismatch must
/// degrade to a clipped screen, not to memory corruption.
pub struct Framebuffer<'a> {
    buffer: &'a mut [u8],
    info: FramebufferInfo,
}

impl<'a> Framebuffer<'a> {
    /// Wrap a caller-supplied pixel buffer. No pixel is touched here;
    /// clearing is the console constructor's job, so a bare buffer
    /// can be inspected before any draw.
    pub fn new(buffer: &'a mut [u8], info: FramebufferInfo) -> Self {
        Framebuffer { buffer, info }
    }

    /// Geometry the adapter reported, for the console's column/row math.
    pub fn info(&self) -> FramebufferInfo {
        self.info
    }

    /// Byte offset of pixel (`x`, `y`), or `None` when the pixel is
    /// outside the geometry or outside the supplied slice.
    fn pixel_offset(&self, x: usize, y: usize) -> Option<usize> {
        if x >= self.info.width || y >= self.info.height {
            return None;
        }
        let bpp = self.info.bytes_per_pixel;
        if bpp == 0 {
            return None;
        }
        let offset = y
            .checked_mul(self.info.stride)?
            .checked_mul(bpp)?
            .checked_add(x.checked_mul(bpp)?)?;
        if offset.checked_add(bpp)? > self.buffer.len() {
            return None;
        }
        Some(offset)
    }

    /// Plot one pixel. Unknown depths (anything other than 1, 3, or 4
    /// bytes per pixel) are left unwritten: this module will not guess
    /// a layout it does not know. At 4 bytes per pixel the pad byte is
    /// set opaque so a compositor never sees a transparent pixel.
    pub fn write_pixel(&mut self, x: usize, y: usize, color: (u8, u8, u8)) {
        let offset = match self.pixel_offset(x, y) {
            Some(offset) => offset,
            None => return,
        };
        let (r, g, b) = color;
        match (self.info.pixel_format, self.info.bytes_per_pixel) {
            (PixelFormat::Gray, 1) => {
                let lum = ((r as u16 * 30 + g as u16 * 59 + b as u16 * 11) / 100) as u8;
                self.buffer[offset] = lum;
            }
            (PixelFormat::Rgb, 3) => {
                self.buffer[offset] = r;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = b;
            }
            (PixelFormat::Bgr, 3) => {
                self.buffer[offset] = b;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = r;
            }
            (PixelFormat::Rgb, 4) => {
                self.buffer[offset] = r;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = b;
                self.buffer[offset + 3] = 0xFF;
            }
            (PixelFormat::Bgr, 4) => {
                self.buffer[offset] = b;
                self.buffer[offset + 1] = g;
                self.buffer[offset + 2] = r;
                self.buffer[offset + 3] = 0xFF;
            }
            _ => {}
        }
    }

    /// Fill the whole screen with one color.
    pub fn clear(&mut self, color: (u8, u8, u8)) {
        for y in 0..self.info.height {
            for x in 0..self.info.width {
                self.write_pixel(x, y, color);
            }
        }
    }

    /// Fill a pixel rectangle, clipped to the screen by `write_pixel`.
    pub fn fill_rect(&mut self, x: usize, y: usize, w: usize, h: usize, color: (u8, u8, u8)) {
        for row in y..y.saturating_add(h) {
            for col in x..x.saturating_add(w) {
                self.write_pixel(col, row, color);
            }
        }
    }

    /// Scroll the screen up by `lines` pixel rows: every row moves up
    /// and the freed rows at the bottom are painted `fill`. Each
    /// destination row's bytes are copied from the source row below it
    /// with `copy_within`, which handles the overlap; the destination
    /// is always above the source, so no row is read after overwrite.
    pub fn scroll_up_pixels(&mut self, lines: usize, fill: (u8, u8, u8)) {
        if lines == 0 || lines >= self.info.height {
            if lines >= self.info.height && self.info.height > 0 {
                self.clear(fill);
            }
            return;
        }
        let bpp = self.info.bytes_per_pixel;
        if bpp == 0 {
            return;
        }
        let row_bytes = self.info.stride.saturating_mul(bpp);
        let height = self.info.height;
        for y in 0..height - lines {
            let dst = y.saturating_mul(row_bytes);
            let src = y.saturating_add(lines).saturating_mul(row_bytes);
            if src.checked_add(row_bytes).map_or(true, |end| end > self.buffer.len())
                || dst.checked_add(row_bytes).map_or(true, |end| end > self.buffer.len())
            {
                continue;
            }
            // Copy within the slice, destination above source: safe in order.
            self.buffer.copy_within(src..src + row_bytes, dst);
        }
        self.fill_rect(0, height - lines, self.info.width, lines, fill);
    }

    /// Draw one glyph cell with its top-left corner at pixel (`x`, `y`).
    /// Bit 7 of each font byte is the leftmost pixel. Every pixel of
    /// the cell is painted, foreground for set bits and background for
    /// clear bits, so a redrawn cell never leaves stale pixels behind.
    pub fn draw_glyph(&mut self, x: usize, y: usize, ch: u8, fg: (u8, u8, u8), bg: (u8, u8, u8)) {
        let glyph = FONT_8X16[ch as usize];
        for row in 0..FONT_HEIGHT {
            let bits = glyph[row];
            for col in 0..FONT_WIDTH {
                let set = bits & (0x80 >> col) != 0;
                self.write_pixel(x + col, y + row, if set { fg } else { bg });
            }
        }
    }
}

/// A text console over a framebuffer: character cells, a cursor, and
/// scrolling. Columns and rows are derived from the geometry, so a
/// framebuffer narrower than one glyph cell yields zero columns and
/// every write is a no-op rather than a wrap-around bug.
pub struct FramebufferConsole<'a> {
    fb: Framebuffer<'a>,
    col: usize,
    row: usize,
    fg: (u8, u8, u8),
    bg: (u8, u8, u8),
}

impl<'a> FramebufferConsole<'a> {
    /// Build a console and clear the screen to the background color.
    pub fn new(fb: Framebuffer<'a>, fg: (u8, u8, u8), bg: (u8, u8, u8)) -> Self {
        let mut console = FramebufferConsole { fb, col: 0, row: 0, fg, bg };
        let bg_color = console.bg;
        console.fb.clear(bg_color);
        console
    }

    /// Character columns across the screen (zero on a sub-cell screen).
    pub fn cols(&self) -> usize {
        self.fb.info().width / FONT_WIDTH
    }

    /// Character rows down the screen (zero on a sub-cell screen).
    pub fn rows(&self) -> usize {
        self.fb.info().height / FONT_HEIGHT
    }

    /// Move the cursor (demo splash: lets the boot spin redraw the
    /// same rows instead of scrolling; mirrors vga.rs set_pos).
    /// Clamped inside the screen; a sub-cell screen parks at 0,0.
    pub fn set_pos(&mut self, row: usize, col: usize) {
        if self.rows() == 0 || self.cols() == 0 {
            self.row = 0;
            self.col = 0;
            return;
        }
        self.row = row.min(self.rows() - 1);
        self.col = col.min(self.cols() - 1);
    }

    /// Move to the start of the next line, scrolling when past the bottom.
    fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        if self.row >= self.rows() {
            if self.rows() > 0 {
                let bg_color = self.bg;
                self.fb.scroll_up_pixels(FONT_HEIGHT, bg_color);
                self.row = self.rows() - 1;
            } else {
                self.row = 0;
            }
        }
    }

    /// Write one byte. `\n` moves to the next line, `\r` returns to
    /// column zero, `0x08` backspaces (KF-03: the shell erases with
    /// the "\x08 \x08" sequence, so the framebuffer console must
    /// blank the cell like vga.rs does, not ignore the byte),
    /// printable and high bytes (0x20..=0xFF) draw their
    /// glyph from the 256-entry table, and other control bytes are
    /// ignored rather than drawn as glyph noise.
    pub fn write_byte(&mut self, byte: u8) {
        match byte {
            b'\n' => self.newline(),
            b'\r' => self.col = 0,
            0x08 => self.backspace(),
            0x20..=0xFF => {
                if self.cols() == 0 || self.rows() == 0 {
                    return;
                }
                let x = self.col * FONT_WIDTH;
                let y = self.row * FONT_HEIGHT;
                let fg_color = self.fg;
                let bg_color = self.bg;
                self.fb.draw_glyph(x, y, byte, fg_color, bg_color);
                self.col += 1;
                if self.col >= self.cols() {
                    self.newline();
                }
            }
            _ => {}
        }
    }

    /// Write a string, byte by byte. Non-ASCII UTF-8 bytes draw their
    /// Latin-2 glyphs individually; this is a byte console, not a
    /// Unicode renderer, and that limit is stated, not hidden.
    pub fn write_str(&mut self, s: &str) {
        for byte in s.bytes() {
            self.write_byte(byte);
        }
    }

    /// Erase the cell left of the cursor (KF-03, mirrors
    /// vga.rs backspace): move back one cell and repaint it with
    /// the background color. At column 0, wrap to the previous
    /// row's last cell; at the top-left cell, a no-op. On a
    /// sub-cell screen (zero columns) there is no cell to erase.
    pub fn backspace(&mut self) {
        if self.cols() == 0 {
            return;
        }
        if self.col > 0 {
            self.col -= 1;
        } else if self.row > 0 {
            self.row -= 1;
            self.col = self.cols() - 1;
        } else {
            return;
        }
        let bg = self.bg;
        self.fb
            .draw_glyph(self.col * FONT_WIDTH, self.row * FONT_HEIGHT, b' ', bg, bg);
    }

    /// Fill the screen with the background color (KF-03: the shell
    /// `clear` command and the panic screen need this on the
    /// framebuffer exactly as they have it on VGA).
    pub fn clear(&mut self) {
        let bg = self.bg;
        self.fb.clear(bg);
    }

    /// Change colors; already-drawn cells keep their colors
    /// (KF-03: mirrors vga.rs set_colors for the panic screen and
    /// the shell status block).
    pub fn set_colors(&mut self, fg: (u8, u8, u8), bg: (u8, u8, u8)) {
        self.fg = fg;
        self.bg = bg;
    }
}

impl core::fmt::Write for FramebufferConsole<'_> {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        FramebufferConsole::write_str(self, s);
        Ok(())
    }
}

