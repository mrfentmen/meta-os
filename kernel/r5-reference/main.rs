/// Stable entry point for the asm stub. `no_mangle` so the stub's
/// `call kernel_interrupt_dispatch` resolves at link time. The frame
/// pointer is valid by the trampoline contract above; nothing else
/// calls this function.
#[no_mangle]
pub extern "C" fn kernel_interrupt_dispatch(
    vector: u64,
    frame: *const interrupts::InterruptFrame,
    error_code: u64,
) {
    unsafe {
        interrupts::dispatch(vector as u8, &*frame, error_code);
    }
}

/// Read the live code-segment selector instead of asserting a
/// bootloader GDT constant: whatever segment the bootloader entered
/// with is the segment the IDT gates must name.
fn read_cs() -> u16 {
    let cs: u16;
    unsafe {
        core::arch::asm!("mov {0:x}, cs", out(reg) cs,
            options(nomem, nostack, preserves_flags));
    }
    cs
}

/// Install sequence, exactly as `kernel/src/interrupts.rs` documents
/// it: cli, fill the dispatch table, install one present interrupt
/// gate (0x8E) per vector with the live CS and no IST, verify each
/// gate round-trips through `idt_get()` (fail-stop on mismatch:
/// enabling interrupts over a broken table would triple-fault),
/// remap the PICs to 32/40, set the PIT to 100 Hz, lidt, sti.
fn install_interrupts() {
    interrupts::disable();
    interrupts::register_builtins();
    let cs = read_cs();
    let mut vector: u16 = 0;
    while vector <= 255 {
        let v = vector as u8;
        let addr = trampoline_addr(v);
        interrupts::idt_set(v, interrupts::IdtEntry::new(addr, cs, 0, 0x8E));
        if interrupts::idt_get(v).handler_addr() != addr {
            serial_write_str("META OS KERNEL - idt mismatch\n");
            loop {
                core::hint::spin_loop();
            }
        }
        vector += 1;
    }
    interrupts::pic_remap(0x20, 0x28);
    interrupts::pit_set_hz(100);
    unsafe {
        interrupts::load_idt();
    }
    interrupts::enable();
}

fn kernel_main(_boot_info: &'static bootloader::BootInfo) -> ! {
    serial_init();
    serial_write_str("META OS KERNEL - alive (K1)\n");
    install_interrupts();
    serial_write_str("META OS KERNEL - interrupts on (R5)\n");
    loop {
        core::hint::spin_loop();
    }
}

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    serial_write_str("META OS KERNEL - panic\n");
    loop {
        core::hint::spin_loop();
    }
}
