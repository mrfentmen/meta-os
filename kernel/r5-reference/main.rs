//! Meta OS kernel, milestone K1 + R5 (interrupts wired).
//!
//! K1: boots under the rust-osdev bootloader, initialises the COM1 serial
//! port with raw port IO (no external crates), prints the alive line,
//! and halts in a spin loop. The QEMU serial log showing that line is
//! the K1 proof (proven 2026-11-01 on the Mac: os-build/logs/K1-boot*.txt).
//!
//! R5 (this commit, interrupts only): `mod interrupts` is wired into
//! `kernel_main` below: the 256 asm trampolines in the `global_asm!`
//! block install one present interrupt gate per vector, the dispatch
//! table is filled with the R3 built-in handlers, and the install
//! sequence runs (cli, PIC remap to 32/40, PIT 100 Hz, lidt, sti).
//! Status, exactly: WRITTEN, NOT A KERNEL-CRATE COMPILE, NOT A BOOT
//! VERDICT. This code counts only when it builds on the boss's Mac
//! and a QEMU boot shows interrupt behavior (a keyboard line prints
//! on keypress; an unhandled vector prints its line; the timer tick
//! count is observable through `ticks()` but not printed, so a tick
//! print would be a flood, not a proof). Until then no interrupt is
//! claimed to work.
//!
//! Q9 (handler ABI) proposed answer, subject to Milo gate-1 + Pax merge
//! + Mac boot proof: asm trampolines, per the R3 module contract in
//! `kernel/src/interrupts.rs` (a Rust `fn` is never asserted as an IDT
//! entry point). If the Mac build prefers `extern "x86-interrupt"`,
//! these trampolines get replaced; nothing here claims the decision.
//!
//! Framebuffer is NOT wired by this commit. Reason, checked this run:
//! at the resolved bootloader 0.9.35, `BootInfo` carries no framebuffer
//! (docs.rs bootloader 0.9.34 `bootinfo/mod.rs` source read in full:
//! only `memory_map`, `recursive_page_table_addr`,
//! `physical_memory_offset`, `tls_template`, `recursive_index` — no
//! framebuffer member or method; the 0.9.35 `BootInfo` docs show the
//! same field set; the framebuffer-carrying `BootInfo` belongs to the
//! later `bootloader_api` split, not 0.9.x). The R5 framebuffer adapter
//! therefore has no source to adapt from, and Q5 needs a re-answer:
//! VGA mode-13 buffer, a bootloader upgrade, or OpenCode Section B.
//! That call is Pax's; until he makes it, `mod framebuffer` stays out
//! of this file and no framebuffer claim is made.
//!
//! No mocks (KERNEL_SPEC.md rule 6): every gate points at a real
//! trampoline, every handler is the R3 module's real handler, and the
//! IDT round-trip check below fail-stops on a mismatch instead of
//! enabling interrupts over a broken table.

