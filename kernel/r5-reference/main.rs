/// The trampoline address table emitted by the `global_asm!` block
/// below: one `.quad` per vector, in vector order. Read-only after
/// link; the only consumer is `trampoline_addr()`.
extern "C" {
    static tramp_table: [u64; 256];
}

fn trampoline_addr(vector: u8) -> u64 {
    unsafe { tramp_table[vector as usize] }
}

