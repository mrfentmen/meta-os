#!/usr/bin/env python3
"""Service shim vs kernel dispatch — a tripwire, not a cheerleader.

`services/common/sys/sys.goose` declares the six calls every Layer-4 service
is written against, with the transport deliberately open. `kernel/src/user.rs`
implements six syscalls, but they are NOT the same six: the names, the return
shapes and one whole call (ticks) differ. That mismatch is the K6 gap, and it
is easy to lose track of because both sides "have six calls".

This script states the mapping, marks the differences, and FAILS when either
side changes so the docs and the lane plan get updated in the same commit.
It does not claim a service can run on the kernel; it says exactly which calls
would work and which would not.

Usage:
  abi_contract.py            # check + print
  abi_contract.py --write    # also rewrite ABI_CONTRACT_STATUS.md
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SYS_GOOSE = os.path.join(REPO, "services", "common", "sys", "sys.goose")
USER_RS = os.path.join(REPO, "kernel", "src", "user.rs")
STATUS_MD = os.path.join(REPO, "os-build", "ABI_CONTRACT_STATUS.md")

# What this file asserts about the world on 2026-11-02. When Rowan closes a
# gap, the check fails and forces this table + the status doc to change; that
# is the point. Do not "fix" a failure by widening the expectation silently.
MAPPING = {
    "sys_exit":         {"arm": 0, "state": "SERVED"},
    "sys_write_serial": {"arm": 1, "state": "SERVED"},
    "sys_write_console": {"arm": 1, "state": "SERVED"},
    "sys_read_key":     {"arm": 5, "state": "SHAPE DIFFERS"},
    "sys_ticks":        {"arm": None, "state": "MISSING"},
    "sys_yield":        {"arm": 4, "state": "SERVED"},
}

SHAPE_NOTES = {
    "sys_write_serial": "kernel write() prints to serial AND console; one page per call",
    "sys_write_console": "same kernel arm as write_serial, so the two cannot fail independently yet",
    "sys_read_key": "kernel returns a scancode in RAX (u64::MAX = empty); the shim wants bool + caller buffer + out_len",
    "sys_ticks": "no syscall exists; the kernel's tick counter is internal (interrupts::ticks)",
}


def shim_calls():
    text = open(SYS_GOOSE, "r", encoding="utf-8").read()
    return re.findall(r"extern fn (\w+)\s*\(", text)


def kernel_arms():
    text = open(USER_RS, "r", encoding="utf-8").read()
    start = text.find("match num {")
    if start < 0:
        raise SystemExit("abi_contract: no `match num {` in kernel/src/user.rs")
    body = text[start:]
    end = body.find("\n        }\n    }")
    if end < 0:
        end = len(body)
    body = body[:end]
    arms = {}
    for match in re.finditer(r"^\s*(\d+)\s*=>", body, re.MULTILINE):
        arms[int(match.group(1))] = True
    return arms


def build_rows():
    calls = shim_calls()
    arms = kernel_arms()
    rows = []
    problems = []
    for call in calls:
        expect = MAPPING.get(call)
        if expect is None:
            problems.append(f"{call}: shim call has no row in MAPPING (add one)")
            rows.append((call, "-", "UNKNOWN", ""))
            continue
        arm = expect["arm"]
        state = expect["state"]
        if state != "MISSING":
            if arm not in arms:
                problems.append(f"{call}: expects kernel arm {arm}, user.rs has no such arm")
            note = SHAPE_NOTES.get(call, "")
        else:
            if arm is not None:
                problems.append(f"{call}: marked MISSING but names arm {arm}")
            note = SHAPE_NOTES.get(call, "")
        rows.append((call, str(arm) if arm is not None else "—", state, note))
    # Reserved range must still be empty: the F1 ruling, not an accident.
    for n in range(6, 16):
        if n in arms:
            problems.append(f"kernel arm {n} exists; 6-15 are reserved by the F1 ruling")
    return rows, problems


def render(rows):
    lines = [
        "# ABI contract status — service shim vs kernel dispatch",
        "",
        "Generated by `os-build/userspace/abi_contract.py --write` on 2026-11-02.",
        "Source of truth: `services/common/sys/sys.goose` (what services call) and",
        "`kernel/src/user.rs` (what the kernel actually serves).",
        "",
        "**No Goose service can run on the kernel yet.** Four calls map cleanly onto",
        "kernel arms, `sys_read_key` maps to arm 5 but with a different return shape,",
        "and `sys_ticks` has no syscall at all. Two of the four share one arm, so a",
        "dead UART and a dead display are not distinguishable yet.",
        "",
        "| service call | kernel arm | state | note |",
        "|---|---|---|---|",
    ]
    for call, arm, state, note in rows:
        lines.append(f"| `{call}` | {arm} | **{state}** | {note} |")
    lines += [
        "",
        "## What closing this needs",
        "",
        "1. `sys_ticks` — a syscall returning `interrupts::ticks()`; number must be",
        "   assigned by Pax (6-15 are reserved by the F1 ruling), then implemented by",
        "   Rowan in `user.rs`.",
        "2. `sys_read_key(out, cap, out_len)` — either a new call or an ABI change to",
        "   arm 5; today a service cannot tell \"no key\" from \"scancode 0\" without",
        "   reading the sentinel contract, which is not the shim's contract.",
        "3. `sys_write_serial` / `sys_write_console` — currently one arm. A dead UART",
        "   must be distinguishable from a dead display, so these need separate paths",
        "   before `logd` can trust either.",
        "4. A process model: the kernel embeds four static ELFs and has four user",
        "   stack slots. Services need spawn, and that is `KERNEL_BUILDOUT_SPEC.md`",
        "   K4/K6 work, not a service change.",
        "",
        "The tripwire: this script fails if either file changes, so the gap cannot",
        "close quietly.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description="service shim vs kernel dispatch")
    ap.add_argument("--write", action="store_true", help="rewrite ABI_CONTRACT_STATUS.md")
    args = ap.parse_args(argv)

    rows, problems = build_rows()
    print(f"{'service call':<20} {'arm':>4}  state")
    for call, arm, state, _note in rows:
        print(f"{call:<20} {arm:>4}  {state}")
    if args.write:
        with open(STATUS_MD, "w", encoding="utf-8") as fh:
            fh.write(render(rows))
        print(f"wrote {os.path.relpath(STATUS_MD, REPO)}")
    if problems:
        print("\ntripwire: the mapping changed — update MAPPING, this doc and the lane plan")
        for p in problems:
            print(f"  FAIL {p}")
        return 1
    counts = {}
    for _call, _arm, state, _note in rows:
        counts[state] = counts.get(state, 0) + 1
    summary = ", ".join(f"{n} {state.lower()}" for state, n in sorted(counts.items()))
    print(f"\n{len(rows)} service calls checked: {summary}; arms 6-15 still reserved")
    return 0


if __name__ == "__main__":
    sys.exit(main())
