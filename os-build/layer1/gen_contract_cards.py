#!/usr/bin/env python3
"""os-build/layer1/gen_contract_cards.py -- surface cards for services without a contract.

The hand-written contract pages in `contracts/` state what a service PROMISES: the rules it
enforces, what it refuses, what a restart costs. Ten services have one. Writing thirty by
hand would be thirty essays, and most of them would be a restatement of the function list.

This tool writes the other kind: a SURFACE CARD, generated from the source. It says what the
service exports, what limits it declares, which drivers reach it, and where the reader should
look for the promises. It cannot be wrong about a function signature, and it does not claim to
know a rule the source does not show -- that distinction is in the card's first paragraph.

A service with a hand-written page in `contracts/` is skipped: the essay wins.

Usage:  python3 os-build/layer1/gen_contract_cards.py [--write]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SERVICES = os.path.join(ROOT, "services")
CONTRACTS = os.path.join(HERE, "contracts")

FN = re.compile(r"^fn\s+([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*(->\s*[^\{]+)?", re.M)
CONST = re.compile(r"^let\s+([A-Z][A-Z0-9_]*)\s*:\s*i64\s*=\s*([^;]+);(.*)$", re.M)
IMPORT = re.compile(r"^import\s+([A-Za-z0-9_]+)\.([A-Za-z0-9_]+);", re.M)
STATUS = re.compile(r"^//\s*Status:\s*(.*)$", re.M)
TITLE_COMMENT = re.compile(r"^//\s*(.+)$", re.M)


def header(path):
    """The first paragraph of the file's leading comment block, as the purpose line."""
    with open(path, "r", encoding="utf-8") as h:
        text = h.read()
    lines = []
    for line in text.split("\n"):
        if not line.startswith("//"):
            if lines:
                break
            continue
        body = line[2:].strip()
        if body.startswith("services/") or body == "":
            if lines and body == "":
                break
            continue
        if body.isupper() and len(body) > 4:
            break
        lines.append(body)
    return " ".join(lines).strip()


def service_dirs():
    out = []
    for name in sorted(os.listdir(SERVICES)):
        p = os.path.join(SERVICES, name)
        if not os.path.isdir(p) or name in ("common", "tests", "build"):
            continue
        if any(f.endswith(".goose") for f in os.listdir(p)):
            out.append(name)
    return out


def card(name):
    files = sorted(f for f in os.listdir(os.path.join(SERVICES, name)) if f.endswith(".goose"))
    main = os.path.join(SERVICES, name, files[0])
    purpose = header(main)
    imports, fns, consts, status = set(), [], [], ""
    total_lines = 0
    for f in files:
        path = os.path.join(SERVICES, name, f)
        with open(path, "r", encoding="utf-8") as h:
            text = h.read()
        total_lines += text.count("\n")
        for m in IMPORT.finditer(text):
            if m.group(1) not in ("common", name):
                imports.add(m.group(1))
        for m in FN.finditer(text):
            ret = (m.group(3) or "").strip()
            ret = re.sub(r"^->\s*", "", ret).strip()
            fns.append((f, m.group(1), m.group(2).strip(), ret or "—"))
        for m in CONST.finditer(text):
            note = m.group(3).strip()
            note = note[2:].strip() if note.startswith("//") else ""
            consts.append((m.group(1), m.group(2).strip(), note))
        st = STATUS.search(text)
        if st and not status:
            status = st.group(1)
    # Which drivers name this service? The test list is the evidence, so it belongs here.
    drivers = []
    tests = os.path.join(SERVICES, "tests")
    for t in sorted(os.listdir(tests)):
        if not t.endswith(".goose"):
            continue
        with open(os.path.join(tests, t), "r", encoding="utf-8") as h:
            body = h.read()
        if re.search(r"^import\s+%s\." % re.escape(name), body, re.M):
            drivers.append(t[:-6])
    return {
        "name": name,
        "files": files,
        "purpose": purpose,
        "imports": sorted(imports),
        "fns": fns,
        "consts": consts,
        "status": status,
        "drivers": drivers,
        "lines": total_lines,
    }


def render(c):
    out = []
    out.append("# Surface card — `%s`" % c["name"])
    out.append("")
    out.append("**Generated by `gen_contract_cards.py` from the source.** This is the surface, not the")
    out.append("contract: it lists what the service exports and which limits it declares. The promises")
    out.append("are in the tests named at the bottom, and the design argument is in the file's own")
    out.append("header comment. A service with a hand-written page in `contracts/` does not get a card")
    out.append("— that page wins.")
    out.append("")
    if c["purpose"]:
        out.append("> " + c["purpose"])
        out.append("")
    if c["status"]:
        out.append("**Status:** %s" % c["status"])
        out.append("")
    out.append("| Fact | Value |")
    out.append("|---|---|")
    out.append("| Files | %s |" % ", ".join("`%s`" % f for f in c["files"]))
    out.append("| Lines | %d |" % c["lines"])
    out.append("| Imports | %s |" % (", ".join("`%s`" % i for i in c["imports"]) or "none"))
    out.append("| Drivers | %d |" % len(c["drivers"]))
    out.append("")
    out.append("## Exported surface")
    out.append("")
    out.append("| File | Function | Parameters | Returns |")
    out.append("|---|---|---|---|")
    for f, name, params, ret in c["fns"]:
        out.append("| `%s` | `%s` | %s | %s |"
                   % (f, name, params.replace("|", "\\|") or "—", ret.replace("|", "\\|")))
    out.append("")
    out.append("## Limits declared")
    out.append("")
    if c["consts"]:
        out.append("| Constant | Value | Note in source |")
        out.append("|---|---|---|")
        for name, value, note in c["consts"]:
            out.append("| `%s` | `%s` | %s |" % (name, value, note.replace("|", "\\|") or "—"))
        out.append("")
        out.append("Whether each one is actually enforced is `LIMITS.md`'s question, and it answers")
        out.append("per constant: PROVEN with a test, EXPLAINED with a reason, or OPEN.")
    else:
        out.append("None.")
    out.append("")
    out.append("## The evidence")
    out.append("")
    if c["drivers"]:
        out.append("Drivers that import this service: " +
                   ", ".join("`%s`" % d for d in c["drivers"]) + ".")
        out.append("")
        out.append("```sh")
        out.append("./os-build/layer1/run_native.sh " + " ".join(c["drivers"]))
        out.append("```")
    else:
        out.append("No driver imports this service. Nothing in the corpus executes it, so nothing here")
        out.append("is proven by running — the surface above is read off the source.")
    out.append("")
    return "\n".join(out)


def main(argv):
    os.makedirs(CONTRACTS, exist_ok=True)
    written, skipped = [], []
    for name in service_dirs():
        hand = os.path.join(CONTRACTS, "%s.md" % name)
        if os.path.exists(hand):
            skipped.append(name)
            continue
        card_text = render(card(name))
        target = os.path.join(CONTRACTS, "%s-surface.md" % name)
        if "--write" in argv:
            with open(target, "w", encoding="utf-8") as h:
                h.write(card_text)
        written.append(name)
    print("cards: %d written/updated, %d skipped (hand-written page exists)"
          % (len(written), len(skipped)))
    if written:
        print("  " + ", ".join(written))
    if skipped:
        print("  hand-written: " + ", ".join(skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
