// Boot-log index generator (R11-282).
//
// Scans the committed logs and writes BOOTLOG_INDEX.md. The index records what each file IS and
// which milestone its filename claims; it does not adjudicate the claim unless the boot markers
// are present, and it says so in the table. Re-run it when a log lands:
//   node os-build/layer1/gen_bootlog_index.mjs
import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.dirname(path.dirname(HERE));
const logsDir = path.join(root, "os-build", "logs");
const out = path.join(HERE, "BOOTLOG_INDEX.md");

const MARKERS = [
  ["META OS KERNEL - alive", "K1 alive"],
  ["K3 timer:", "K3 timer"],
  ["mem summary: K4 up", "K4 memory"],
  ["K5 scheduler", "K5 scheduler"],
  ["HELLO FROM USERSPACE", "K6 ring 3"],
  ["user exit code 0", "K6 clean exit"],
  ["task killed", "K6 fault isolation"],
  ["loader refused", "O-3 regression (loader refused)"],
  ["META OS 0.1", "K1 banner"],
];

function describe(file) {
  const text = fs.readFileSync(file, "utf8");
  const found = MARKERS.filter(([needle]) => text.includes(needle)).map(([, label]) => label);
  const ansi = /\x1b\[/.test(text);
  return {
    name: path.basename(file),
    bytes: fs.statSync(file).size,
    lines: text.split("\n").length,
    serial: !ansi,
    markers: found,
    first: (text.match(/META OS[^\n]*/) || [""])[0],
  };
}

const rows = fs.readdirSync(logsDir)
  .filter((f) => f.endsWith(".txt"))
  .sort()
  .map((f) => describe(path.join(logsDir, f)));

const md = [];
md.push("# Boot-log index (R11-282)");
md.push("");
md.push("Generated by `os-build/layer1/gen_bootlog_index.mjs` on " + new Date().toISOString().slice(0, 10) + ".");
md.push("Every committed `os-build/logs/*.txt` is listed. **`serial`** means the file is serial console output");
md.push("(readable); a file with ANSI/VGA escapes is a display capture, not a serial log, and is marked so.");
md.push("**Markers found** are literal boot lines present in the file. The index does NOT decide that a");
md.push("milestone is proven; the gate and the reviewer still do that.");
md.push("");
md.push("| log | bytes | lines | serial | markers found | first META line |");
md.push("|---|---|---|---|---|---|");
for (const r of rows) {
  md.push("| `" + r.name + "` | " + r.bytes + " | " + r.lines + " | " + (r.serial ? "yes" : "no (display)") +
    " | " + (r.markers.length ? r.markers.join(", ") : "none") + " | " + (r.first ? "`" + r.first.replace(/\|/g, "\\|") + "`" : "—") + " |");
}
md.push("");
md.push("## What this index cannot tell you");
md.push("");
md.push("- When a log was produced. The filename and the git commit are the only timestamps; a file's");
md.push("  mtime is checkout time, not boot time.");
md.push("- Whether the run that wrote it was on the same commit as the tree you are reading.");
md.push("- Whether a boot the log does not mention was attempted. A missing log is not a failed boot.");
md.push("");
fs.writeFileSync(out, md.join("\n"));
console.log("wrote " + path.relative(root, out) + " (" + rows.length + " logs)");
