#!/usr/bin/env python3
"""os-build/layer1/deadcode.py -- E6: what is written and never called.

The corpus has no compiler that can report this: Goose compiles a function that nothing
calls and clang keeps it if it is exported. So the census is textual, and it is stated as
such below every number it prints.

Three questions, in order of how much they cost to be wrong:

  1. FUNCTIONS with no reference at all -- not in a driver, not in their own file, not in
     another service. These are the ones a reviewer reads and assumes are load-bearing.
  2. CONSTANTS declared and never read. A limit nothing reads is not a limit; it is a
     comment with a type, and the audit that names it as "explained" may be explaining an
     intention instead of a fact.
  3. ACCESSORS that only a test calls. Not dead, but it means the public surface is larger
     than the code the system actually runs, and every extra function is a promise.

Usage:  python3 os-build/layer1/deadcode.py [--write]
Exit:   0 always -- this is a census, not a gate. The findings are the output.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SERVICES = os.path.join(ROOT, "services")
DEST = os.path.join(HERE, "DEADCODE.md")

FN = re.compile(r"^fn\s+([A-Za-z0-9_]+)\s*\(", re.M)
CONST = re.compile(r"^let\s+([A-Z][A-Z0-9_]*)\s*:\s*i64\s*=", re.M)
EXTERN = re.compile(r"^extern\s+fn\s+([A-Za-z0-9_]+)", re.M)
STRUCT = re.compile(r"^struct\s+([A-Za-z0-9_]+)", re.M)


def sources():
    """(path, kind) for every Goose file, kind in service/library/test/other."""
    out = []
    for base, _dirs, names in os.walk(SERVICES):
        for n in sorted(names):
            if not n.endswith(".goose"):
                continue
            path = os.path.join(base, n)
            rel = os.path.relpath(path, SERVICES)
            parts = rel.split(os.sep)
            if parts[0] == "tests":
                kind = "test"
            elif parts[0] == "common":
                kind = "library"
            elif parts[0] == "build":
                kind = "other"
            else:
                kind = "service"
            out.append((path, kind))
    return out


def main(argv):
    files = sources()
    texts = {}
    for path, _kind in files:
        with open(path, "r", encoding="utf-8") as h:
            texts[path] = h.read()

    def refs(name, skip_path=None, skip_line=0):
        """Count references to `name` as a whole word, optionally outside one definition."""
        pat = re.compile(r"\b%s\b" % re.escape(name))
        test_refs = 0
        other_refs = 0
        for path, text in texts.items():
            for m in pat.finditer(text):
                if path == skip_path:
                    line = text.count("\n", 0, m.start())
                    if line == skip_line:
                        continue
                kind = dict(files)[path]
                if kind == "test":
                    test_refs += 1
                else:
                    other_refs += 1
        return other_refs, test_refs

    kinds = dict(files)
    dead_fns, test_only_fns, dead_consts, dead_structs = [], [], [], []

    for path, kind in files:
        text = texts[path]
        if kind == "test":
            continue
        rel = os.path.relpath(path, ROOT)
        for m in FN.finditer(text):
            name = m.group(1)
            line = text.count("\n", 0, m.start())
            other, tests = refs(name, path, line)
            if other == 0 and tests == 0:
                dead_fns.append((rel, name, line + 1))
            elif other == 0:
                test_only_fns.append((rel, name, line + 1, tests))
        for m in CONST.finditer(text):
            name = m.group(1)
            line = text.count("\n", 0, m.start())
            other, tests = refs(name, path, line)
            if other == 0 and tests == 0:
                dead_consts.append((rel, name, line + 1))
        for m in STRUCT.finditer(text):
            name = m.group(1)
            line = text.count("\n", 0, m.start())
            other, tests = refs(name, path, line)
            if other == 0 and tests == 0:
                dead_structs.append((rel, name, line + 1))

    services = len([1 for _p, k in files if k == "service"])
    lines = [
        "# Dead-code census (E6)",
        "",
        "Generated by `python3 os-build/layer1/deadcode.py`. **Textual, not compiled:** a name is",
        "\"referenced\" if it appears as a whole word anywhere in `services/` other than its own",
        "definition line. That over-counts references (a name in a comment counts) and it is the",
        "reason this page under-reports dead code rather than inventing any: a function that only",
        "appears in a comment will not be listed here, and the page says so instead of claiming",
        "a compiler's answer.",
        "",
        "Scanned: %d service directories, %d Goose files." % (services, len(files)),
        "",
        "## 1. Functions nothing calls",
        "",
    ]
    if dead_fns:
        lines += ["| File | Function | Line |", "|---|---|---|"]
        for rel, name, line in dead_fns:
            lines.append("| `%s` | `%s` | %d |" % (rel, name, line))
    else:
        lines.append("None. Every function in the tree is referenced by something.")
    lines += ["", "## 2. Constants nothing reads", ""]
    if dead_consts:
        lines += ["| File | Constant | Line |", "|---|---|---|"]
        for rel, name, line in dead_consts:
            lines.append("| `%s` | `%s` | %d |" % (rel, name, line))
        lines += ["", "A constant in this list is a limit that does not exist. `gen_limits.py` may",
                  "still classify it as EXPLAINED, and that classification is about the intention,",
                  "not about enforcement."]
    else:
        lines.append("None. Every limit constant is read by the code that enforces it.")
    lines += ["", "## 3. Structs nothing uses", ""]
    if dead_structs:
        lines += ["| File | Struct | Line |", "|---|---|---|"]
        for rel, name, line in dead_structs:
            lines.append("| `%s` | `%s` | %d |" % (rel, name, line))
    else:
        lines.append("None.")
    lines += ["", "## 4. Functions only a test calls", "",
              "Not dead, and not a defect: these are the accessors a driver reads to check a",
              "service's state. They are listed because the public surface is larger than the code",
              "the system runs, and every accessor is a promise somebody may rely on later.", "",
              "| File | Function | Line | Test references |", "|---|---|---|---|"]
    for rel, name, line, tests in sorted(test_only_fns, key=lambda t: (t[0], t[2])):
        lines.append("| `%s` | `%s` | %d | %d |" % (rel, name, line, tests))
    # Breakdown by directory: a service with six unreferenced functions is a different
    # problem from a library with six, and the number alone does not say which.
    by_dir = {}
    for rel, name, line in dead_fns:
        key = rel.split(os.sep)[1]
        by_dir[key] = by_dir.get(key, 0) + 1
    lines += ["", "## Where they are", "", "| Directory | Unreferenced functions |", "|---|---|"]
    for key in sorted(by_dir, key=lambda k: (-by_dir[k], k)):
        lines.append("| `services/%s` | %d |" % (key, by_dir[key]))
    lines += ["", "## What this census found", ""]
    lines.append("- %d function(s) with no reference at all." % len(dead_fns))
    lines.append("- %d constant(s) declared and never read." % len(dead_consts))
    lines.append("- %d accessor(s) reached only from a driver." % len(test_only_fns))
    lines += ["", "The count that matters for the submission is the first: a function nothing calls",
              "is a claim about the system that the system does not make.", ""]

    page = "\n".join(lines)
    if "--write" in argv:
        with open(DEST, "w", encoding="utf-8") as h:
            h.write(page)
        print("wrote %s" % os.path.relpath(DEST, ROOT))
    else:
        print(page)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
