#!/usr/bin/env bash
# os-build/layer1/boot_rehearsal.sh — BF5-01: execute BOOT_PLAN's order in the host runtime.
#
# What this does: reads the boot order out of the supervisor's own table (BO_NAMES in
# services/supervisor/bootorder.goose — one source, no copy), then for each service in order
# runs its entry binary — built by run_native.sh from services/<svc>/entry.goose — under a
# timeout, capturing the program's stdout verbatim.
#
# What this proves: the entry point of each service starts, prints, and either exits or does
# not. What it does NOT prove: that a kernel started it, that it has an address space, or that
# anything ran concurrently. The services run one after another in one host process each.
#
# A service with no entry binary is reported NO ENTRY, not skipped: the count of services that
# cannot start at all is the most useful number this script produces.
#
# Usage: os-build/layer1/boot_rehearsal.sh [timeout_seconds]
# Exit: 0 when every service either STARTED (exited 0) or is NO ENTRY; 1 when one HANGS.
set -uo pipefail
cd "$(dirname "$0")/../.." || exit 2

TIMEOUT="${1:-5}"
OUT=os-build/layer1/host/build
REH="$OUT/rehearsal"
DOC=os-build/layer1/BOOT_REHEARSAL.md
mkdir -p "$REH"

# The order is the supervisor's table, not a second copy of it — and it is the table's
# `order` column, not the order the names happen to be written in (BO_NAMES is id order, so
# the first version of this script rehearsed callmatrix before bootlog and was wrong).
ORDER=$(python3 - <<'PY'
import re
src = open("services/supervisor/bootorder.goose", encoding="utf-8").read()
names = re.search(r'let BO_NAMES: const u8\[:\] = "([^"]+)"', src)
names = names.group(1).split() if names else []
rows = re.findall(r'BootEntry \{ id: (\d+), needs: \d+, fatal: (?:true|false), '
                  r'by_kernel: (?:true|false), order: (\d+) \}', src)
pairs = [(int(o), names[int(i) - 1]) for i, o in rows
         if 1 <= int(i) <= len(names)]   # id 0 is bo_entry()'s fallback, not a service
print(" ".join(n for _o, n in sorted(pairs)))
PY
)
if [ -z "$ORDER" ]; then
    echo "could not read BO_NAMES from services/supervisor/bootorder.goose" >&2
    exit 2
fi

# Run one binary with a wall-clock bound. macOS has no `timeout`, and a service that hangs is
# a result we want to record rather than a reason to lose the run.
run_bounded() {
    local secs="$1" path="$2" log="$3"
    "$path" >"$log" 2>&1 &
    local pid=$!
    local i=0
    while kill -0 "$pid" 2>/dev/null && [ "$i" -lt $((secs * 10)) ]; do
        sleep 0.1; i=$((i + 1))
    done
    if kill -0 "$pid" 2>/dev/null; then
        kill -9 "$pid" 2>/dev/null
        wait "$pid" 2>/dev/null
        return 124
    fi
    wait "$pid"
    return $?
}

rows=()
n_start=0; n_hang=0; n_fail=0; n_none=0
idx=0
echo "== boot rehearsal, order from bootorder.goose, timeout ${TIMEOUT}s"
for svc in $ORDER; do
    idx=$((idx + 1))
    exe="$OUT/entry_$svc"
    log="$REH/$svc.log"
    if [ ! -x "$exe" ]; then
        n_none=$((n_none + 1))
        rows+=("$idx|$svc|NO ENTRY|—|no services/$svc/entry.goose, or it was not built")
        printf '  %2d  %-11s NO ENTRY\n' "$idx" "$svc"
        continue
    fi
    : >"$log"
    run_bounded "$TIMEOUT" "$exe" "$log"
    rc=$?
    lines=$(wc -l <"$log" | tr -d ' ')
    if [ "$rc" -eq 124 ]; then
        n_hang=$((n_hang + 1))
        rows+=("$idx|$svc|HANGS|$lines|still running after ${TIMEOUT}s; killed")
        printf '  %2d  %-11s HANGS      %s lines, killed after %ss\n' "$idx" "$svc" "$lines" "$TIMEOUT"
    elif [ "$rc" -eq 0 ]; then
        n_start=$((n_start + 1))
        rows+=("$idx|$svc|STARTED|$lines|printed $lines line(s), exited 0")
        printf '  %2d  %-11s STARTED    %s lines, exit 0\n' "$idx" "$svc" "$lines"
    else
        n_fail=$((n_fail + 1))
        rows+=("$idx|$svc|EXITS $rc|$lines|printed $lines line(s), exit $rc")
        printf '  %2d  %-11s EXITS %-3s  %s lines\n' "$idx" "$svc" "$rc" "$lines"
    fi
done

echo
printf 'rehearsed %d services: started=%d  hangs=%d  failed=%d  no-entry=%d\n' \
    "$idx" "$n_start" "$n_hang" "$n_fail" "$n_none"

# ---- the document -------------------------------------------------------------------------
{
    echo "# Boot rehearsal (BF5-01) — executed $(date +%Y-%m-%d)"
    echo
    echo "Generated by \`os-build/layer1/boot_rehearsal.sh\`. The order is read from"
    echo "\`services/supervisor/bootorder.goose\` (\`BO_NAMES\`), and each line below is the"
    echo "program's own stdout, captured to \`os-build/layer1/host/build/rehearsal/<svc>.log\`."
    echo "Regenerate with:"
    echo
    echo '```'
    echo './os-build/layer1/run_native.sh          # builds the entry binaries'
    echo './os-build/layer1/boot_rehearsal.sh 5    # 5s wall clock per service'
    echo '```'
    echo
    echo "**What this is.** $n_none services have no entry point at all, so they cannot be started"
    echo "by anything; the rest were started here, one host process each, in the supervisor's"
    echo "order. That is a rehearsal of the *order and the entry points*, in a host runtime, and"
    echo "it is the closest thing to a boot this layer has."
    echo
    echo "**What this is not.** No kernel started these. There is no address space, no privilege"
    echo "boundary, no scheduler, and no concurrency: service 2 runs after service 1 exits. A"
    echo "service that hangs is killed by this script's timeout, not by the supervisor — because"
    echo "the start timeout the layer promises does not exist (\`FAILURE_TRACE.md\` item 4)."
    echo
    echo "## Result"
    echo
    echo "| # | Service | Outcome | Lines | Note |"
    echo "|---|---|---|---|---|"
    for r in "${rows[@]}"; do
        IFS='|' read -r i s o l n <<<"$r"
        echo "| $i | \`$s\` | **$o** | $l | $n |"
    done
    echo
    echo "**$n_start started, $n_hang hung, $n_fail failed, $n_none could not start (no entry"
    echo "point)** out of $idx services in boot order."
    echo
    echo "## The transcripts"
    for r in "${rows[@]}"; do
        IFS='|' read -r i s o l n <<<"$r"
        echo
        echo "### $i. $s — $o"
        echo
        if [ -s "$REH/$s.log" ]; then
            echo '```'
            head -40 "$REH/$s.log"
            if [ "$(wc -l <"$REH/$s.log" | tr -d ' ')" -gt 40 ]; then
                echo "... ($(wc -l <"$REH/$s.log" | tr -d ' ') lines total, first 40 shown)"
            fi
            echo '```'
        else
            echo "_No output. The program produced nothing before $([ "$o" = "HANGS" ] && echo "the timeout killed it" || echo "it exited")._"
        fi
    done
    echo
    echo "## What the rehearsal found"
    echo
    echo "1. **\`console\` hangs.** It prints its banner, then loops on \`sys_read_key\`; the host"
    echo "   shim answers \"nothing pending\", which is a valid answer, so the loop never ends."
    echo "   This is the start-timeout failure class, demonstrated rather than described:"
    echo "   nothing in this layer can notice it."
    echo "2. **\`time\` starts and says nothing.** Exit 0, zero lines — the entry has no status"
    echo "   line. A service that cannot be seen starting is not proven to have started, which"
    echo "   is why the supervisor's proof line (BOOT_PLAN S7) is specified as a printed line."
    echo "3. **\`bootlog\` and \`logd\` both start cleanly** and print their state, in order, with"
    echo "   the fields the boot record expects."
    echo "4. **$n_none of $idx services cannot start at all** — no \`entry.goose\`. Those are the"
    echo "   real load-plan blockers, named by service in the table above."
} >"$DOC"

echo "wrote $DOC"
[ "$n_hang" -eq 0 ]
