"""Hortus rung-2 calibration: fit discipline and one application.

The calibration (worlds/science-lab/hortus/calibration) is
allowed to claim exactly three things, and these tests pin
them:

1. The fit works: given parts whose measured resistances were
   GENERATED by the model itself under a known h multiplier,
   fitting recovers that multiplier and takes the calibration
   subset's error to (numerically) zero - far below where the
   uncalibrated scorer sits.
2. The validation subset is never fitted against: perturbing
   the validation parts' measured values cannot move the
   fitted multiplier, because the fit never receives them.
3. The calibrated coefficient is applied exactly once:
   calibrated_train_env() / calibrated_held_out_envs() scale
   each h by CALIBRATED_H_MULTIPLIER a single time - not zero
   times, not twice - and leave every other field untouched.

Nothing here validates the toy model against the physical
world; that evidence lives in calibration/CALIBRATION.md and
is exactly as strong as the datasheet comparison it reports.
"""
import os
import sys
import unittest

sys.path.insert(0, ".")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "worlds", "science-lab"))

from hortus import model, verifier  # noqa: E402
from hortus.calibration import check_scorer  # noqa: E402

TRUE_MULTIPLIER = 0.42


def _synthetic_part(part_id, profile, width_mm, n_fins, subset,
                    fin_height_mm=50.8):
    """A part whose 'measured' resistance is the model's own
    prediction under TRUE_MULTIPLIER - a known-offset world in
    which the correct fit is exactly recoverable."""
    part = {
        "part_id": part_id,
        "profile_no": profile,
        "fin_height_in": 2,
        "subset": subset,
        "geometry_mm": {
            "fin_count": n_fins,
            "fin_height_mm": fin_height_mm,
            "fin_thickness_mm": 1.27,
            "base_thickness_mm": 12.7,
            "plate_width_mm": width_mm,
            "plate_length_mm": 152.4,
            "fin_pitch_mm": width_mm / n_fins,
        },
        "measured_thermal_resistance_c_per_w": 0.0,  # filled below
    }
    part["measured_thermal_resistance_c_per_w"] = \
        check_scorer.predicted_resistance(part, TRUE_MULTIPLIER)
    return part


class CalibrationFitTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.calibration = [
            _synthetic_part("SYN-A", "A", 80.0, 12, "calibration"),
            _synthetic_part("SYN-B", "B", 110.0, 18, "calibration"),
            _synthetic_part("SYN-C", "C", 140.0, 22, "calibration",
                            fin_height_mm=101.6),
        ]
        cls.validation = [
            _synthetic_part("SYN-V", "V", 95.0, 15, "validation"),
        ]

    def test_fit_recovers_known_offset(self):
        fitted = check_scorer.fit_multiplier(self.calibration)
        self.assertAlmostEqual(fitted, TRUE_MULTIPLIER, places=3)
        before = check_scorer.summarise(
            check_scorer.error_rows(self.calibration, 1.0))
        after = check_scorer.summarise(
            check_scorer.error_rows(self.calibration, fitted))
        self.assertGreater(before["mean_abs_pct"], 40.0)
        self.assertLess(after["mean_abs_pct"], 0.1)

    def test_validation_subset_is_never_fitted(self):
        fitted_honest = check_scorer.fit_multiplier(self.calibration)
        poisoned = [dict(p) for p in self.validation]
        for part in poisoned:
            part["measured_thermal_resistance_c_per_w"] *= 3.0
        # The fit's input is the calibration subset alone; a
        # corrupted validation subset, never passed to it,
        # cannot move the result.
        fitted_again = check_scorer.fit_multiplier(self.calibration)
        self.assertEqual(fitted_honest, fitted_again)
        # And the poison is real: scored against the poisoned
        # values, the same multiplier's errors DO move - so the
        # invariance above is the fit's discipline, not a dead
        # comparison.
        honest_err = check_scorer.summarise(
            check_scorer.error_rows(self.validation, fitted_honest))
        poisoned_err = check_scorer.summarise(
            check_scorer.error_rows(poisoned, fitted_honest))
        self.assertNotAlmostEqual(honest_err["mean_abs_pct"],
                                  poisoned_err["mean_abs_pct"],
                                  places=3)


class CalibratedEnvTest(unittest.TestCase):

    def test_train_env_scales_h_exactly_once(self):
        env = model.calibrated_train_env()
        self.assertEqual(
            env["h_w_per_m2k"],
            model.TRAIN_ENV["h_w_per_m2k"]
            * model.CALIBRATED_H_MULTIPLIER)
        self.assertNotEqual(
            env["h_w_per_m2k"],
            model.TRAIN_ENV["h_w_per_m2k"]
            * model.CALIBRATED_H_MULTIPLIER ** 2)
        for key, value in model.TRAIN_ENV.items():
            if key not in ("h_w_per_m2k", "name"):
                self.assertEqual(env[key], value)

    def test_held_out_envs_scale_h_exactly_once(self):
        scaled = model.calibrated_held_out_envs()
        self.assertEqual(len(scaled), len(verifier.HELD_OUT_ENVS))
        for raw, cal in zip(verifier.HELD_OUT_ENVS, scaled):
            self.assertEqual(
                cal["h_w_per_m2k"],
                raw["h_w_per_m2k"] * model.CALIBRATED_H_MULTIPLIER)
            for key, value in raw.items():
                if key not in ("h_w_per_m2k", "name"):
                    self.assertEqual(cal[key], value)

    def test_uncalibrated_model_is_untouched(self):
        # The toy model as shipped must reproduce the rung-1
        # run: wiring the calibration in changed no default.
        self.assertNotIn("calibrated", model.TRAIN_ENV["name"])
        self.assertEqual(model.TRAIN_ENV["h_w_per_m2k"], 10.0)
        genome = (20.0, 40.0, 1.5, 3.0)
        self.assertNotEqual(
            model.score(genome, model.TRAIN_ENV),
            model.score(genome, model.calibrated_train_env()))


if __name__ == "__main__":
    unittest.main()
