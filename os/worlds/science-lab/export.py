def _utcnow():
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def _read_json(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def _write_json(path, doc):
    parent = os.path.dirname(os.path.abspath(path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(doc, sort_keys=True, indent=2) + "\n")
    return path


def _ledger_entries(cycle_id=None):
    if _ledger_mod is None:
        return []
    try:
        entries = _ledger_mod.read_all(LEDGER_PATH)
    except OSError:
        return []
    if cycle_id is None:
        return entries
    return [e for e in entries
            if isinstance(e, dict) and e.get("cycle_id") == cycle_id]


def _repository_rows(kind, cycle_id=None):
    if _repository_mod is None:
        return []
    try:
        rows = _repository_mod.query(kind=kind)
    except (OSError, ValueError):
        return []
    if cycle_id is None:
        return rows
    return [r for r in rows
            if isinstance(r, dict) and r.get("cycle_id") == cycle_id]


def _cycle_record(cycle_id):
    path = os.path.join(CYCLES_DIR, "%s.json" % cycle_id)
    if not os.path.exists(path):
        raise FileNotFoundError("no cycle record at %r" % (path,))
    return _read_json(path)


def _guard(level):
    """Ladder guard: a claim displays at its recorded level, never higher."""
    if _ladder_mod is None:
        raise RuntimeError("ladder module unavailable; refusing to export "
                           "levels without the guard")
    if isinstance(level, bool):
        raise ValueError("level must be an int 0-6, got %r" % (level,))
    level = int(level)
    if level not in _ladder_mod.LEVELS:
        raise ValueError("level out of range 0-6: %r" % (level,))
    _ladder_mod.assert_export_allowed(level, level)
    return level


