def run_failure_drill():
    """Break one input mid-cycle; record the behaviour (task 93).

    Breaks the hypotheses input, then attempts the gated transition:
    the machine must refuse (ValueError), park, or fail loudly --
    never fake success. Returns the drill document (filed to
    records/examples/failure_drill.json).
    """
    if _cycle_mod is None or _compute_mod is None:
        raise RuntimeError("failure drill blocked: cycle/compute "
                           "unimportable; refusing to fake the drill.")
    cid = "DRILL-FAILURE-001"
    cyc = _cycle_mod.new_cycle(cid, "Drill: what happens when an input "
                                   "breaks mid-cycle?")
    cyc.setdefault("inputs", {})["sources"] = {"brief": "drill brief"}
    with tempfile.TemporaryDirectory(prefix="scilab-drill-") as tmp:
        ledger_path = os.path.join(tmp, "ledger.jsonl")
        first = _cycle_mod.transition(cyc, "literature",
                                      "drill brief filed", ledger_path)
        assert first["phase"] == "literature"
        # Break it: drop the hypotheses input the next gate requires.
        broken_input = "hypotheses"
        cyc["inputs"].pop("hypotheses", None)
        try:
            _cycle_mod.transition(cyc, "cheap-computations",
                                  "drill advance without hypotheses",
                                  ledger_path)
            behaviour = "UNEXPECTED-SUCCESS (machine advanced without " \
                        "the required input -- bug, reported not hidden)"
            refused = False
            message = ""
        except ValueError as exc:
            behaviour = "refused"
            refused = True
            message = str(exc)
        # A second break: invalid computation input fails loudly.
        try:
            _compute_mod.run_bio({"sequence": "ACGTXXZZ"})
            loud = "UNEXPECTED-SUCCESS"
        except ValueError as exc:
            loud = "refused: %s" % (exc,)
    doc = {
        "cycle_id": cid,
        "broken_input": broken_input,
        "attempted": "transition literature -> cheap-computations with "
                     "the hypotheses input removed",
        "behaviour": behaviour,
        "refused": refused,
        "refusal_message": message,
        "second_probe": "run_bio with invalid bases; behaviour: %s" % loud,
        "fake_success": False,
        "recovery": "re-file the hypotheses input and advance again; no "
                    "phase was duplicated and no result was fabricated.",
        "honesty": [
            "The cycle refused to advance without its required input.",
            "No claim, level, or result was produced by this drill.",
            "Refusal is the correct behaviour: park/refuse/fail loudly, "
            "never fake success.",
        ],
        "generated_at": _utcnow(),
    }
    _write_json(os.path.join(EXAMPLES_DIR, "failure_drill.json"), doc)
    return doc


