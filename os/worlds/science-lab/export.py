    if not args or "--help" in args or "-h" in args:
        sys.stdout.write(_HELP)
        return 0
    if "--review" in args:
        idx = args.index("--review")
        cid = args[idx + 1] if len(args) > idx + 1 \
            and not args[idx + 1].startswith("--") else "CYCLE-EXAMPLE-001"
        out = render_review(cid)
        sys.stdout.write("review written: %s\n" % out)
        return 0
    if "--cycle" in args:
        idx = args.index("--cycle")
        if len(args) <= idx + 1:
            sys.stderr.write("error: --cycle needs an ID\n")
            return 2
        doc = export_session(args[idx + 1])
        sys.stdout.write("exported %s (%d claims)\n"
                         % (doc["cycle_id"], len(doc["claims"])))
        return 0
    if "--archive" in args:
        idx = args.index("--archive")
        if len(args) <= idx + 1:
            sys.stderr.write("error: --archive needs an ID\n")
            return 2
        result = archive_cycle(args[idx + 1])
        sys.stdout.write("archived %s sha256=%s\n"
                         % (result["zip"], result["sha256"]))
        return 0
