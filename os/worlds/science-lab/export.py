def _held_out_rmse(start=DRESS_ROWS[0], stop=DRESS_ROWS[1]):
    dataset = os.path.join(BASE_DIR, "gate", "delaney",
                           "delaney-processed.csv")
    with open(dataset, "rb") as fh:
        file_sha256 = hashlib.sha256(fh.read()).hexdigest()
    with open(dataset, "r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        header = list(reader.fieldnames or [])
        for col in _HELD_OUT_COLUMNS:
            if col not in header:
                raise ValueError("held-out run blocked: column %r not in "
                                 "CSV header %r" % (col, header))
        rows = list(reader)[start:stop]
    if len(rows) != stop - start:
        raise ValueError("held-out run blocked: wanted rows %d-%d, "
                         "archive holds fewer" % (start + 1, stop))
    pred = [float(r[_HELD_OUT_COLUMNS[0]]) for r in rows]
    meas = [float(r[_HELD_OUT_COLUMNS[1]]) for r in rows]
    rmse = math.sqrt(sum((a - b) ** 2 for a, b in zip(pred, meas))
                     / len(rows))
    return {"rmse": rmse, "n": len(rows), "rows": "%d-%d" % (start + 1, stop),
            "file_sha256": file_sha256}


