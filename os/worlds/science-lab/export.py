def colour_for(level):
    """Level -> colour band name. Levels 4+ are amber (human-only)."""
    if isinstance(level, bool):
        raise ValueError("level must be an int 0-6, got %r" % (level,))
    level = int(level)
    if level not in COLOUR_BANDS:
        raise ValueError("unknown evidence level %r (known: 0-6)"
                         % (level,))
    return COLOUR_BANDS[level]


def claim_display(claim):
    """One claim -> display row with level, colour, bias, and auto flag.

    claim needs level (recorded) + statement + basis. The display level
    IS the recorded level (guarded); 4+ renders amber human-only and is
    never marked automatically confirmed.
    """
    if not isinstance(claim, dict):
        raise ValueError("claim_display requires a claim dict")
    raw_level = claim.get("level", claim.get("evidence_level"))
    if raw_level is None:
        raise ValueError("claim %r carries no level" % (claim.get("claim_id"),))
    level = _guard(raw_level)
    statement = claim.get("statement") or claim.get("claim") or "?"
    basis = claim.get("basis")
    if not basis:
        raise ValueError("claim %r carries no one-line basis"
                         % (claim.get("claim_id"),))
    return {
        "claim_id": str(claim.get("claim_id") or claim.get("id") or "?"),
        "statement": str(statement),
        "level": level,
        "colour": colour_for(level),
        "basis": str(basis),
        "automatically_confirmed": bool(
            level <= 3
            and str(claim.get("verdict", "")).strip().lower()
            in ("confirmed", "reproduced", "agree")),
    }


def display_data(cycle_id=None, claims=None):
    """Per-claim display rows, generated from records, never hand-written.

    Pass a cycle_id (reads its export, generating it first when missing)
    or an explicit claims list. Returns [claim_display(...)...].
    """
    if claims is None:
        if not cycle_id:
            raise ValueError("display_data needs a cycle_id or claims")
        doc = export_session(cycle_id)
        claims = doc.get("claims", [])
    return [claim_display(c) for c in claims]


