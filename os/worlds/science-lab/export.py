_VOLATILE_KEYS = ("generated_at",)


def _strip_volatile(node):
    if isinstance(node, dict):
        return {k: _strip_volatile(v) for k, v in node.items()
                if k not in _VOLATILE_KEYS}
    if isinstance(node, list):
        return [_strip_volatile(v) for v in node]
    return node


def _canonical_bytes(doc):
    return json.dumps(_strip_volatile(doc), sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def regen_drill(exports_dir=None):
    """Regenerate exports from records, byte-compare (task 89).

    Regenerates every session export + dept_summary + board into a
    temp dir and compares canonical bytes against the committed
    files, ignoring volatile stamps (generated_at -- stated here, not
    hidden). Returns {"compared", "identical", "diffs", "note"}.
    """
    out_dir = exports_dir or EXPORTS_DIR
    try:
        cycle_ids = sorted(n[:-5] for n in os.listdir(CYCLES_DIR)
                           if n.endswith(".json"))
    except OSError:
        cycle_ids = []
    diffs = []
    compared = 0
    with tempfile.TemporaryDirectory(prefix="scilab-regen-") as tmp:
        for cid in cycle_ids:
            try:
                fresh = export_session(cid, exports_dir=tmp, write=True)
            except (FileNotFoundError, ValueError) as exc:
                diffs.append({"file": "%s.json" % cid,
                              "reason": "regeneration failed: %s" % (exc,)})
                continue
            committed_path = os.path.join(out_dir, "%s.json" % cid)
            if not os.path.exists(committed_path):
                diffs.append({"file": "%s.json" % cid,
                              "reason": "committed export missing"})
                continue
            try:
                committed = _read_json(committed_path)
            except ValueError as exc:
                diffs.append({"file": "%s.json" % cid,
                              "reason": "committed file unparseable: %s"
                                        % (exc,)})
                continue
            compared += 1
            if _canonical_bytes(fresh) != _canonical_bytes(committed):
                diffs.append({"file": "%s.json" % cid,
                              "reason": "bytes differ after regeneration"})
        for name, builder in (("dept_summary.json", build_dept_summary),
                              ("board.json", build_board)):
            try:
                fresh = builder()
            except (OSError, ValueError) as exc:
                diffs.append({"file": name,
                              "reason": "regeneration failed: %s" % (exc,)})
                continue
            committed_path = os.path.join(out_dir, name)
            if not os.path.exists(committed_path):
                diffs.append({"file": name,
                              "reason": "committed export missing"})
                continue
            try:
                committed = _read_json(committed_path)
            except ValueError as exc:
                diffs.append({"file": name,
                              "reason": "committed file unparseable: %s"
                                        % (exc,)})
                continue
            compared += 1
            if _canonical_bytes(fresh) != _canonical_bytes(committed):
                diffs.append({"file": name,
                              "reason": "bytes differ after regeneration"})
    return {
        "compared": compared,
        "identical": not diffs,
        "diffs": diffs,
        "note": "comparison on canonical JSON bytes excluding volatile "
                "keys %s (regeneration timestamps honestly differ)."
                % (list(_VOLATILE_KEYS),),
    }


