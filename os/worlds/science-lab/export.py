        audit = audit_exports()
        drill = regen_drill()
        sys.stdout.write(json.dumps({"audit": audit, "regen": drill},
                                    sort_keys=True, indent=2) + "\n")
        return 0 if (not audit["violations"]
                     and drill["identical"]) else 1
