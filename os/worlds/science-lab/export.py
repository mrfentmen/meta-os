def archive_cycle(cycle_id, archive_dir=None):
    """Bundle a finished cycle's records, hashed, in one command.

    Zip holds: cycles/<id>.json, reports/<id>.md (when present),
    exports/<id>.json (generated when missing), and the cycle's
    ledger slice. Writes records/archive/<id>.zip + <id>.sha256.
    Returns {"zip", "sha256", "files"}.
    """
    if not cycle_id:
        raise ValueError("archive_cycle requires a cycle_id")
    record = _cycle_record(cycle_id)  # raises FileNotFoundError first
    adir = archive_dir or ARCHIVE_DIR
    os.makedirs(adir, exist_ok=True)
    export_path = os.path.join(EXPORTS_DIR, "%s.json" % cycle_id)
    if not os.path.exists(export_path):
        export_session(cycle_id)
    report_path = os.path.join(REPORTS_DIR, "%s.md" % cycle_id)
    ledger_slice = [e for e in _ledger_entries(cycle_id)]
    zip_path = os.path.join(adir, "%s.zip" % cycle_id)
    with tempfile.TemporaryDirectory(prefix="scilab-archive-") as tmp:
        slice_path = os.path.join(tmp, "ledger_slice.json")
        _write_json(slice_path, ledger_slice)
        with zipfile.ZipFile(zip_path, "w",
                             compression=zipfile.ZIP_DEFLATED) as zf:
            zf.write(os.path.join(CYCLES_DIR, "%s.json" % cycle_id),
                     "cycles/%s.json" % cycle_id)
            zf.write(export_path, "exports/%s.json" % cycle_id)
            if os.path.exists(report_path):
                zf.write(report_path, "reports/%s.md" % cycle_id)
            zf.write(slice_path, "ledger_slice.json")
            manifest = {
                "cycle_id": cycle_id,
                "phase": record.get("phase"),
                "gate_state": record.get("gate_state"),
                "ledger_entries": len(ledger_slice),
                "archived_at": _utcnow(),
            }
            zf.writestr("manifest.json",
                        json.dumps(manifest, sort_keys=True, indent=2)
                        + "\n")
    with open(zip_path, "rb") as fh:
        digest = hashlib.sha256(fh.read()).hexdigest()
    sha_path = os.path.join(adir, "%s.sha256" % cycle_id)
    with open(sha_path, "w", encoding="utf-8") as fh:
        fh.write("%s  %s.zip\n" % (digest, cycle_id))
    with zipfile.ZipFile(zip_path, "r") as zf:
        files = sorted(zf.namelist())
    return {"zip": zip_path, "sha256": digest, "sha_file": sha_path,
            "files": files}


