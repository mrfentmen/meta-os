def _iter_claim_dicts(node, path=""):
    """Yield (path, dict) for every claim-like dict in a JSON doc.

    Claim-like = dict with an int 'level' AND ('claim_id' or
    'statement' or 'basis'). Aggregates (dept_summary/board counts)
    never match this shape, so they are never audited as claims.
    """
    if isinstance(node, dict):
        level = node.get("level")
        if (isinstance(level, int) and not isinstance(level, bool)
                and (node.get("claim_id") is not None
                     or node.get("statement") is not None
                     or node.get("basis") is not None)):
            yield (path or "$", node)
        for key, value in node.items():
            for found in _iter_claim_dicts(
                    value, "%s.%s" % (path or "$", key)):
                yield found
    elif isinstance(node, list):
        for i, value in enumerate(node):
            for found in _iter_claim_dicts(
                    value, "%s[%d]" % (path or "$", i)):
                yield found


def audit_exports(exports_dir=None):
    """Scan exports: no claim above its recorded level.

    Checks internal consistency (level <= recorded_level) and, where
    the claim names a ledger source hash, cross-checks the ledger
    entry's evidence_level. Returns {"exports_scanned",
    "claims_checked", "violations": [...]}. A clean tree has zero
    violations; anything else is returned (never swallowed).
    """
    out_dir = exports_dir or EXPORTS_DIR
    try:
        names = sorted(n for n in os.listdir(out_dir)
                       if n.endswith(".json"))
    except OSError:
        names = []
    ledger_levels = {}
    for entry in _ledger_entries():
        h = entry.get("entry_hash")
        if h and entry.get("evidence_level") is not None:
            try:
                ledger_levels[str(h)] = int(entry["evidence_level"])
                ledger_levels[str(h)[:12]] = int(entry["evidence_level"])
            except (TypeError, ValueError):
                pass
    violations = []
    checked = 0
    for name in names:
        try:
            doc = _read_json(os.path.join(out_dir, name))
        except ValueError as exc:
            violations.append({"file": name, "path": "$",
                               "reason": "unparseable JSON: %s" % (exc,)})
            continue
        for path, claim in _iter_claim_dicts(doc):
            checked += 1
            try:
                level = int(claim["level"])
            except (TypeError, ValueError):
                violations.append({"file": name, "path": path,
                                   "reason": "non-int level %r"
                                   % (claim.get("level"),)})
                continue
            recorded = claim.get("recorded_level", level)
            try:
                recorded = int(recorded)
            except (TypeError, ValueError):
                violations.append({"file": name, "path": path,
                                   "reason": "non-int recorded_level %r"
                                   % (claim.get("recorded_level"),)})
                continue
            if level > recorded:
                violations.append({
                    "file": name, "path": path,
                    "claim_id": claim.get("claim_id"),
                    "reason": "display level %d above recorded level %d"
                              % (level, recorded)})
                continue
            source_hash = None
            for key in ("ledger_entry", "entry_hash", "entry"):
                value = claim.get(key)
                if isinstance(value, str) and len(value) >= 8:
                    source_hash = value
                    break
            if source_hash and source_hash in ledger_levels:
                if level > ledger_levels[source_hash]:
                    violations.append({
                        "file": name, "path": path,
                        "claim_id": claim.get("claim_id"),
                        "reason": "display level %d above ledger "
                                  "evidence_level %d for entry %s"
                                  % (level, ledger_levels[source_hash],
                                     source_hash[:12])})
    return {"exports_scanned": len(names), "claims_checked": checked,
            "violations": violations}


