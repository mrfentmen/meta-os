_LEVEL_RE = re.compile(r"\b[Ll]evel\s+([0-6])\b")
_HEX_RE = re.compile(r"\b[0-9a-f]{8,64}\b")
_RECORD_WORDS = ("ledger", "repository", "records/", "sealed",
                 "entry_hash", "cycle_example", "export", "claim-",
                 "claim_", "EXP-", "CYCLE-", "DRESS-", "DRILL-")


def _prose_hits(path):
    hits = []
    try:
        with open(path, "r", encoding="utf-8") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return hits
    for i, line in enumerate(lines):
        if "claim" not in line.lower():
            continue
        for match in _LEVEL_RE.finditer(line):
            window = "\n".join(lines[max(0, i - 3):i + 4])
            hits.append({"file": path, "line": i + 1,
                         "level": int(match.group(1)),
                         "text": line.strip()[:200], "window": window})
    return hits


def audit_own_claims():
    """Audit every level-claim in our docs/exports -> its record.

    Structured JSON claims (exports/examples + review cards) must sit
    at or below their recorded level (ledger cross-checked where a
    source hash is stated). Prose claim lines (docs containing the
    word 'claim' + a level) must name a record within 3 lines.
    Anything unbacked lands in cut_or_levelled (never silently
    dropped). Returns {"checked", "backed", "cut_or_levelled",
    "notes"}.
    """
    checked, backed, cut = [], [], []
    exports = audit_exports()
    for name in sorted(os.listdir(EXPORTS_DIR) or []):
        if not name.endswith(".json"):
            continue
        path = os.path.join(EXPORTS_DIR, name)
        try:
            doc = _read_json(path)
        except ValueError:
            continue
        for at, claim in _iter_claim_dicts(doc):
            item = {"file": "records/exports/%s" % name, "path": at,
                    "claim_id": claim.get("claim_id"), "level": claim.get(
                        "level"), "recorded_level": claim.get(
                        "recorded_level", claim.get("level"))}
            checked.append(item)
            bad = [v for v in exports["violations"]
                   if v.get("file") == name and v.get("path") == at]
            if bad:
                cut.append({"item": item, "action": "cut or level down "
                            "to the recorded level",
                            "reason": bad[0]["reason"]})
            else:
                backed.append(item)
    review_page = os.path.join(REVIEW_DIR, "index.html")
    if os.path.exists(review_page):
        with open(review_page, "r", encoding="utf-8") as fh:
            page = fh.read()
        cards = re.findall(
            r'data-claim="([^"]+)"\s+data-level="(\d)"', page)
        for claim_id, level in cards:
            item = {"file": "labs/science-lab-review/index.html",
                    "claim_id": claim_id, "level": int(level)}
            checked.append(item)
            m = re.search(r"Record:\s*%s" % re.escape(claim_id), page)
            if m:
                backed.append(item)
            else:
                cut.append({"item": item, "action": "cut the card",
                            "reason": "no record reference on the card"})
    for rel in ("SCIENCE_LAB_STATUS.md", "README.md"):
        path = os.path.join(BASE_DIR, rel)
        if not os.path.exists(path):
            continue
        for hit in _prose_hits(path):
            window = hit.pop("window")
            item = dict(hit)
            item["file"] = "os/worlds/science-lab/%s" % rel
            checked.append(item)
            low = (item["text"] + "\n" + window).lower()
            if _HEX_RE.search(window) or any(
                    w in low for w in _RECORD_WORDS):
                backed.append(item)
            else:
                cut.append({"item": item, "action": "cut or add the "
                            "record reference",
                            "reason": "claim line names no record"})
    return {
        "checked": len(checked),
        "backed": backed,
        "cut_or_levelled": cut,
        "notes": [
            "Definitions of the ladder (no claim attached) are not "
            "claims and are not audited as such.",
            "Unbacked items are listed in cut_or_levelled, never "
            "silently dropped.",
        ],
    }


