#!/usr/bin/env python3
"""tokens_to_slideshow.py — generate the installer slideshow.

Calamares walks through these while it writes the disk. The screen is the
installer's only voice, so it says what is happening and what is about to
happen, in the same palette as the menu, the splash and the login screen.

    python3 iso/tools/tokens_to_slideshow.py            write show.qml
    python3 iso/tools/tokens_to_slideshow.py --check    exit 1 if it is stale
"""

import json
import sys
from pathlib import Path

ISO = Path(__file__).resolve().parents[1]
TOKENS = ISO / "contracts" / "tokens.json"
OUT = ISO / "calamares" / "branding" / "meta" / "show.qml"

SLIDES = (
    ("Installing MetaOS",
     "This takes a few minutes. Nothing leaves this machine unless you send it."),
    ("One dock, five programs",
     "Files, Terminal, Settings, Web, and the agent status reader."),
    ("Blue on black",
     "The boot menu, the splash, the login screen and this installer share one palette."),
    ("When this finishes",
     "The machine restarts to a login screen. The account you create here is the only one."),
)

HEAD = """// Generated by iso/tools/tokens_to_slideshow.py. Do not edit by hand.
// Calamares reads this while it installs. Colours come from the frozen
// contract, so the installer cannot drift from the screens around it.

import QtQuick 2.0
import calamares.slideshow 1.0

Presentation {
    id: presentation

    Timer {
        interval: 9000
        running: true
        repeat: true
        onTriggered: presentation.goToNextSlide()
    }
"""

SLIDE = """
    Slide {
        Rectangle { anchors.fill: parent; color: "%(black)s" }

        Rectangle {
            width: 300; height: 300; radius: 150
            anchors.horizontalCenter: parent.horizontalCenter
            anchors.verticalCenter: parent.verticalCenter
            anchors.verticalCenterOffset: -120
            color: "transparent"
            border.color: "%(blue)s"
            border.width: 8
        }

        Text {
            anchors.horizontalCenter: parent.horizontalCenter
            anchors.top: parent.verticalCenter
            anchors.topMargin: 90
            text: "%(title)s"
            color: "%(white)s"
            font.pixelSize: 40
            font.bold: true
        }

        Text {
            anchors.horizontalCenter: parent.horizontalCenter
            anchors.top: parent.verticalCenter
            anchors.topMargin: 150
            width: parent.width * 0.62
            horizontalAlignment: Text.AlignHCenter
            wrapMode: Text.WordWrap
            text: "%(body)s"
            color: "%(white)s"
            opacity: 0.62
            font.pixelSize: 20
        }
    }
"""


def build(tokens):
    parts = [HEAD]
    for title, body in SLIDES:
        parts.append(SLIDE % {
            "black": tokens["black"],
            "blue": tokens["blue"],
            "white": tokens["white"],
            "title": title,
            "body": body,
        })
    parts.append("}\n")
    return "".join(parts)


def main(argv):
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    show = build(tokens)

    if "--check" in argv:
        if not OUT.is_file():
            print("slideshow: %s is missing" % OUT.relative_to(ISO))
            return 1
        if OUT.read_text(encoding="utf-8") != show:
            print("slideshow: %s is stale (run tokens_to_slideshow.py)" % OUT.relative_to(ISO))
            return 1
        print("slideshow: %s is current" % OUT.relative_to(ISO))
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(show, encoding="utf-8")
    print("slideshow: wrote %s (%d slides)" % (OUT.relative_to(ISO), len(SLIDES)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
