#!/usr/bin/env python3
"""tokens_to_gtk.py — generate the GTK colour sheet from the frozen contract.

The contract lives in `iso/contracts/tokens.json`. This turns it into
`@define-color` names GTK3 understands, so the desktop cannot drift from the
splash or the start page.

    python3 iso/tools/tokens_to_gtk.py            write the CSS
    python3 iso/tools/tokens_to_gtk.py --check    exit 1 if the file is stale
"""

import json
import sys
from pathlib import Path

ISO = Path(__file__).resolve().parents[1]
TOKENS = ISO / "contracts" / "tokens.json"
OUT = ISO / "theme" / "gtk" / "metaos.css"
GREETER_OUT = ISO / "theme" / "lightdm" / "themes" / "MetaOS" / "gtk-3.0" / "gtk.css"
GREETER_THEME = ISO / "theme" / "lightdm" / "themes" / "MetaOS" / "index.theme"

BODY = """
/* Window surfaces */
window, .background {{
  background-color: @meta_black;
  color: @meta_white;
}}
headerbar, .titlebar {{
  background-color: shade(@meta_black, 1.25);
  color: @meta_white;
  border-color: shade(@meta_black, 1.6);
}}
button {{
  background-color: shade(@meta_black, 1.5);
  color: @meta_white;
  border-color: shade(@meta_blue, 0.8);
}}
button:hover {{ background-color: @meta_blue; color: @meta_white; }}
entry, textview {{
  background-color: shade(@meta_black, 1.35);
  color: @meta_white;
  caret-color: @meta_cyan;
}}
selection {{ background-color: @meta_blue; color: @meta_white; }}
menu, popover {{ background-color: shade(@meta_black, 1.3); color: @meta_white; }}
tooltip {{ background-color: @meta_black; color: @meta_white; }}
scrollbar slider {{ background-color: shade(@meta_blue, 0.7); }}

/* One accent, used the same way everywhere */
.accent {{ color: @meta_cyan; }}
.warning {{ color: @meta_gold; }}
.error   {{ color: @meta_pink; }}
.success {{ color: @meta_emerald; }}
"""


GREETER_BODY = """
/* The greeter draws the wallpaper itself; this keeps text and controls
   readable on top of it. */
#lightdm-gtk-greeter { background-color: transparent; color: @meta_white; }
#lightdm-gtk-greeter #panel_window {
  background-color: alpha(@meta_black, 0.72);
  color: @meta_white;
}
#lightdm-gtk-greeter #login_window,
#lightdm-gtk-greeter #greeter_box {
  background-color: alpha(@meta_black, 0.80);
  border-color: alpha(@meta_blue, 0.55);
  color: @meta_white;
}
#lightdm-gtk-greeter entry {
  background-color: alpha(@meta_black, 0.90);
  color: @meta_white;
  caret-color: @meta_cyan;
  border-color: alpha(@meta_blue, 0.70);
}
#lightdm-gtk-greeter button,
#lightdm-gtk-greeter button:hover {
  background-color: alpha(@meta_blue, 0.85);
  color: @meta_white;
}
#lightdm-gtk-greeter label,
#lightdm-gtk-greeter .dim-label { color: alpha(@meta_white, 0.85); }
#lightdm-gtk-greeter .error { color: @meta_pink; }
"""


def build(tokens):
    lines = ["/* Generated by iso/tools/tokens_to_gtk.py. Do not edit by hand. */"]
    for name in sorted(tokens):
        lines.append("@define-color meta_%s %s;" % (name, tokens[name]))
    return "\n".join(lines) + "\n" + BODY


def greeter_css(tokens):
    lines = ["/* Generated by iso/tools/tokens_to_gtk.py. Do not edit by hand. */"]
    for name in sorted(tokens):
        lines.append("@define-color meta_%s %s;" % (name, tokens[name]))
    return "\n".join(lines) + "\n" + GREETER_BODY


THEME_INDEX = """[Desktop Entry]
Type=X-GNOME-Metatheme
Name=MetaOS
Comment=MetaOS colours for the login screen
Encoding=UTF-8
"""


def main(argv):
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    targets = ((OUT, build(tokens)), (GREETER_OUT, greeter_css(tokens)))

    stale = 0
    for path, css in targets:
        if "--check" in argv:
            if not path.is_file():
                print("gtk: %s is missing" % path.relative_to(ISO))
                stale = 1
            elif path.read_text(encoding="utf-8") != css:
                print("gtk: %s is stale (run tokens_to_gtk.py)" % path.relative_to(ISO))
                stale = 1
            else:
                print("gtk: %s is current" % path.relative_to(ISO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(css, encoding="utf-8")
            print("gtk: wrote %s" % path.relative_to(ISO))

    if "--check" not in argv and not GREETER_THEME.is_file():
        GREETER_THEME.parent.mkdir(parents=True, exist_ok=True)
        GREETER_THEME.write_text(THEME_INDEX, encoding="utf-8")
        print("gtk: wrote %s" % GREETER_THEME.relative_to(ISO))
    return stale


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
