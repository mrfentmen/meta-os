#!/usr/bin/env python3
"""tokens_to_grub.py — generate the GRUB menu theme from the frozen contract.

GRUB draws before Plymouth and before the greeter, so it is the first screen
that can disagree about a colour. This file is generated from the same tokens
as the other two, and the checker compares the committed bytes with what this
tool would write now.

    python3 iso/tools/tokens_to_grub.py            write theme.txt
    python3 iso/tools/tokens_to_grub.py --check    exit 1 if it is stale
"""

import json
import sys
from pathlib import Path

ISO = Path(__file__).resolve().parents[1]
TOKENS = ISO / "contracts" / "tokens.json"
OUT = ISO / "boot" / "grub" / "themes" / "metaos" / "theme.txt"
IMAGE = "meta-grub.png"

TEMPLATE = """# Generated by iso/tools/tokens_to_grub.py. Do not edit by hand.
# Only colours from the contract and one image beside this file. No font is
# named: GRUB would look for a .pf2 that nothing here can build, and render
# nothing at all. Its own font applies.

desktop-image: "{image}"
desktop-image-scale-method: "stretch"
desktop-image-h-align: "center"
desktop-image-v-align: "center"

title-text: "MetaOS"
title-color: "{white}"

+ boot_menu {{
  left = 12%
  top = 30%
  width = 56%
  height = 48%
  item_color = "{white}"
  selected_item_color = "{blue}"
  item_height = 26
  item_spacing = 10
}}
"""


def build(tokens):
    return TEMPLATE.format(image=IMAGE, white=tokens["white"], blue=tokens["blue"])


def main(argv):
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    theme = build(tokens)

    if "--check" in argv:
        if not OUT.is_file():
            print("grub: %s is missing" % OUT.relative_to(ISO))
            return 1
        if OUT.read_text(encoding="utf-8") != theme:
            print("grub: %s is stale (run tokens_to_grub.py)" % OUT.relative_to(ISO))
            return 1
        print("grub: %s is current" % OUT.relative_to(ISO))
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(theme, encoding="utf-8")
    print("grub: wrote %s" % OUT.relative_to(ISO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
